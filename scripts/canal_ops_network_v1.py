def write_json(path, obj):
    path.write_text(json.dumps(obj, indent=1, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")


def build(out=OUT, cfg=CFG):
    out = Path(out); out.mkdir(parents=True, exist_ok=True)
    lines = load_canal(cfg)
    net = build_network(load_universe(cfg), lines, Terrain.load(cfg), cfg)
    br, gt = net["branches"].copy(), net["gates"].copy()
    br["lon"], br["lat"] = to_wgs(br.x, br.y, cfg)
    gt["lon"], gt["lat"] = to_wgs(gt.x, gt.y, cfg)
    pg = net["parcels"].reset_index()
    for c in ("chainage_m", "distance_m", "elev"):
        pg[c] = pg[c].round(1)
    pg = pg[PARCEL_COLS]
    old = out / "parcel_gate.parquet"
    changes = id_changes(pd.read_parquet(old), pg) if old.exists() else id_changes(pg.iloc[:0], pg)
    br[BRANCH_COLS].to_parquet(out / "branches.parquet", index=False)
    gt[GATE_COLS].to_parquet(out / "gates.parquet", index=False)
    pg.to_parquet(out / "parcel_gate.parquet", index=False)
    changes.to_parquet(out / "id_changes.parquet", index=False)
    write_json(out / "network.geojson", network_geojson(net, lines, cfg))
    summary = summarize(net, lines, cfg)
    summary["id_changes"] = {f"{k}_{s}": int(v) for (k, s), v in changes.groupby(["kind", "status"]).size().items()}
    write_json(out / "summary.json", summary)
    inputs = [cfg["inputs"][k] for k in ("canal", "communities", "land_types", "land_type_map", "terrain", "terrain_meta")]
    write_json(out / "manifest.json", {
        "version": cfg["version"], "script": "scripts/canal_ops_network_v1.py", "script_sha256": sha(Path(__file__)),
        "config": "config/canal_ops_network_v1.json", "config_sha256": sha(CFG_PATH),
        "inputs": {k: sha(ROOT / k) for k in inputs},
        "outputs": {f.name: sha(f) for f in sorted(out.iterdir()) if f.name != "manifest.json"},
        "internal_only": ["parcel_gate.parquet", "id_changes.parquet"],
        "not_used": cfg["inputs"]["not_used"]})
    return summary


