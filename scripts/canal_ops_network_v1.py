"""Synthetic canal network for canal_ops_sim_v1 (plan v5, owner 2026-11-01: "I am not using data, it's synthetic").

Only the main canal line is real (data/source/lower_hrazdan.geojson, stages I and II). Offtakes, gate/pump types, gates
and branches are generated by the fixed rules in config/canal_ops_network_v1.json over the Lower Hrazdan observed zone
parcels (land types v1.4, field and perennial classes). The SQL archive and every archive-derived layer are NOT read.

  1. Chainage in metres (EPSG:32638) along each stage, from 0 at its upstream end.
  2. Each parcel centroid goes to the nearest stage line: chainage, distance, canal side.
  3. Parcels are grouped by (stage, community, 1.5 km chainage window); one offtake per group at the floor of the
     group's minimum chainage to 250 m (a group under 10 ha joins its community's neighbouring group). Type "pump" when the group's median terrain is >= 3 m above the canal there,
     else "gate" ("type by terrain rule, synthetic"). Parcels beyond the max distance, without a location or outside
     the community outlines are "unassigned", never forced (G2.4).
  4. Each offtake's parcels are split per canal side into contiguous 10-30 ha gates (G2.5); a parcel over 30 ha is its
     own gate. IDs are hashes of the offtake and the sorted parcel ids; each rebuild writes an old-to-new ID table.
  5. Tree: canal stage -> branch (offtake head, labels I-B1.. in chainage order) -> gate. Branch geometry is a dashed
     schematic spur from the offtake to each gate centroid, capped in length, for display only (G2.6).

  canal_ops_network_v1.py build   -> data/analysis/canal_ops_sim_v1/network/
     branches.parquet, gates.parquet     public aggregates (no parcel ids or cadastral codes)
     parcel_gate.parquet                 per parcel (internal only; never served)
     id_changes.parquet                  old -> new branch and gate ids against the previous build
     network.geojson                     canal + offtakes + gates + schematic spurs (no parcel ids or cadastral codes)
     summary.json (QA), manifest.json (sha256 of inputs and outputs)
"""
