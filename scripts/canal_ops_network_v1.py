def to_wgs(x, y, cfg=CFG):
    from pyproj import Transformer
    t = Transformer.from_crs(cfg["crs"], "EPSG:4326", always_xy=True)
    lon, lat = t.transform(np.asarray(x, dtype=float), np.asarray(y, dtype=float))
    return np.round(lon, 6), np.round(lat, 6)


def network_geojson(net, lines, cfg=CFG):
    br, gt = net["branches"], net["gates"]
    lab = cfg["labels"]
    feats = []
    for stage, line in lines.items():
        xy = np.asarray(line.coords)
        lon, lat = to_wgs(xy[:, 0], xy[:, 1], cfg)
        feats.append({"type": "Feature", "properties": {"kind": "main_canal", "stage": cfg["canal"]["stages"][stage]["label"],
                      "length_m": round(line.length), "basis": "real main canal line, chainage from the upstream end"},
                      "geometry": {"type": "LineString", "coordinates": np.column_stack([lon, lat]).tolist()}})
    lon, lat = to_wgs(br.x, br.y, cfg)
    for r, x, y in zip(br.itertuples(), lon, lat):
        feats.append({"type": "Feature", "properties": {
            "kind": "offtake", "branch": r.branch, "label": r.label, "stage": r.stage, "community": r.community,
            "chainage_m": r.chainage_m, "offtake_type": r.offtake_type, "type_basis": r.type_basis, "n_gates": int(r.n_gates),
            "ha": round(r.ha, 1), "synthetic": True}, "geometry": {"type": "Point", "coordinates": [x, y]}})
    glon, glat = to_wgs(gt.x, gt.y, cfg)
    slon, slat = to_wgs(gt.spur_x, gt.spur_y, cfg)
    olon, olat = to_wgs(gt.branch.map(br.set_index("branch").x), gt.branch.map(br.set_index("branch").y), cfg)
    for i, r in enumerate(gt.itertuples()):
        props = {"gate": r.gate, "label": r.label, "branch_label": r.branch_label, "community": r.community}
        feats.append({"type": "Feature", "properties": {"kind": "gate", **props, "ha": round(r.ha, 1),
                      **{f"ha_{lt}": round(getattr(r, f"ha_{lt}"), 1) for lt in LTYPES}, "synthetic": True},
                      "geometry": {"type": "Point", "coordinates": [glon[i], glat[i]]}})
        feats.append({"type": "Feature", "properties": {"kind": "branch_spur", **props, "dashed": True, "schematic": True,
                      "truncated": r.spur_truncated, "label_text": lab["spur"]},
                      "geometry": {"type": "LineString", "coordinates": [[olon[i], olat[i]], [slon[i], slat[i]]]}})
    return {"type": "FeatureCollection", "name": cfg["version"], "label": lab["network"], "zone": lab["zone"], "features": feats}


