def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def short_hash(text, n):
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:n]


# ---------------------------------------------------------------- canal
def orient_lines(raw, cfg=CFG):
    """raw: {stage: LineString in metres}. Returns lines running from the upstream end, in config stage order."""
    out = {}
    for stage, s in cfg["canal"]["stages"].items():
        line = raw[stage]
        out[stage] = LineString(line.coords[::-1]) if s["upstream_end"] == "last" else line
    return out


def load_canal(cfg=CFG):
    from pyproj import Transformer
    from shapely.ops import transform
    to_m = Transformer.from_crs("EPSG:4326", cfg["crs"], always_xy=True).transform
    feats = json.loads((ROOT / cfg["inputs"]["canal"]).read_text(encoding="utf-8"))["features"]
    return orient_lines({f["properties"]["stage"]: transform(to_m, shape(f["geometry"])) for f in feats}, cfg)


def upstream_offsets(lines, cfg=CFG):
    """Distance from the canal head to the start of each stage (stage II draws through stage I)."""
    out = {}
    for stage, s in cfg["canal"]["stages"].items():
        up = s.get("draws_through")
        out[stage] = round(lines[up].length + out.get(up, 0.0), 1) if up else 0.0
    return out


# ---------------------------------------------------------------- terrain
class Terrain:
    """North-up grid in the network CRS: elevation[row, col], transform (a, b, c, d, e, f) as in the .json sidecar."""

    def __init__(self, elevation, transform):
        self.z = np.asarray(elevation, dtype=float)
        self.a, _, self.c, _, self.e, self.f = tuple(transform)[:6]

    @classmethod
    def load(cls, cfg=CFG):
        meta = json.loads((ROOT / cfg["inputs"]["terrain_meta"]).read_text(encoding="utf-8"))
        assert meta["crs"] == cfg["crs"], meta["crs"]
        return cls(np.load(ROOT / cfg["inputs"]["terrain"], allow_pickle=False)["elevation"], meta["transform"])

    def _rc(self, x, y):
        col = np.floor((np.asarray(x, dtype=float) - self.c) / self.a)
        row = np.floor((np.asarray(y, dtype=float) - self.f) / self.e)
        ok = np.isfinite(col) & np.isfinite(row) & (col >= 0) & (row >= 0) & (col < self.z.shape[1]) & (row < self.z.shape[0])
        return row, col, ok

    def at(self, x, y):
        row, col, ok = self._rc(x, y)
        out = np.full(row.shape, np.nan)
        out[ok] = self.z[row[ok].astype(int), col[ok].astype(int)]
        return out

    def window_median(self, x, y, radius):
        row, col, ok = self._rc([x - radius, x + radius], [y + radius, y - radius])
        r0, r1 = int(np.clip(row[0], 0, self.z.shape[0])), int(np.clip(row[1] + 1, 0, self.z.shape[0]))
        c0, c1 = int(np.clip(col[0], 0, self.z.shape[1])), int(np.clip(col[1] + 1, 0, self.z.shape[1]))
        w = self.z[r0:r1, c0:c1]
        w = w[np.isfinite(w)]
        return float(np.median(w)) if w.size else np.nan


def canal_profile(lines, terrain, cfg=CFG):
    """Terrain along each stage every profile_step_m: median in a reference window around the line point."""
    c = cfg["canal"]
    rows = []
    for stage, line in lines.items():
        for ch in np.arange(0.0, line.length + 1e-9, c["profile_step_m"]):
            pt = line.interpolate(ch)
            rows.append({"stage": stage, "chainage_m": float(ch), "elev": terrain.window_median(pt.x, pt.y, c["reference_radius_m"])})
    return pd.DataFrame(rows)


def canal_elevation(profile, stage, chainage, cfg=CFG):
    c = cfg["canal"]
    p = profile[(profile.stage == stage) & profile.elev.notna()]
    near = p[(p.chainage_m - chainage).abs() <= c["offtake_window_m"]]
    if len(near):
        return float(near.elev.median()), "canal terrain at offtake"
    if len(p):
        k = (p.chainage_m - chainage).abs()
        if k.min() <= c["fallback_max_m"]:
            return float(p.elev[k == k.min()].iloc[0]), "nearest covered canal terrain"
    return np.nan, "terrain not covered"


def orientation_check(profile, lines, span_m=2000.0):
    """The canal must fall downstream: median terrain of the first vs the last covered 2 km of each stage."""
    out = {}
    for stage in lines:
        p = profile[(profile.stage == stage) & profile.elev.notna()]
        lo, hi = p.chainage_m.min(), p.chainage_m.max()
        up = float(p.elev[p.chainage_m <= lo + span_m].median())
        down = float(p.elev[p.chainage_m >= hi - span_m].median())
        out[stage] = {"length_m": round(lines[stage].length, 1), "covered_from_m": float(lo), "covered_to_m": float(hi),
                      "upstream_elev_m": round(up, 1), "downstream_elev_m": round(down, 1), "falls_downstream": bool(up > down)}
    return out


# ---------------------------------------------------------------- parcels
def load_universe(cfg=CFG):
    """Observed-zone parcels (land types v1.4 field + perennial classes) with metric centroid coordinates."""
    from pyproj import Transformer
    from season_replay_v1 import load_parcels
    p = load_parcels()[["community", "area_ha", "ltype"]]
    ll = pd.read_parquet(ROOT / cfg["inputs"]["land_types"], columns=["internal_parcel_id", "lon", "lat"]).set_index("internal_parcel_id")
    p = p.join(ll)
    x, y = Transformer.from_crs("EPSG:4326", cfg["crs"], always_xy=True).transform(p.lon.to_numpy(), p.lat.to_numpy())
    p["x"], p["y"] = x, y
    return p.drop(columns=["lon", "lat"]).sort_index()


def project(x, y, lines):
    """Nearest stage line for each point: stage, chainage (m from the stage's upstream end), distance, side of flow."""
    x, y = np.asarray(x, dtype=float), np.asarray(y, dtype=float)
    ok = np.isfinite(x) & np.isfinite(y)
    pts = shapely.points(np.where(ok, x, 0.0), np.where(ok, y, 0.0))
    names = list(lines)
    dist = np.vstack([shapely.distance(pts, lines[s]) for s in names])
    k = dist.argmin(0)                                    # ties go to the first stage in config order
    stage = np.array(names, dtype=object)[k]
    chain = np.zeros(len(x)); side = np.full(len(x), None, dtype=object)
    for i, s in enumerate(names):
        m = k == i
        if not m.any():
            continue
        line = lines[s]
        c = shapely.line_locate_point(line, pts[m])
        p0 = shapely.line_interpolate_point(line, np.clip(c - 1.0, 0, line.length))
        p1 = shapely.line_interpolate_point(line, np.clip(c + 1.0, 0, line.length))
        x0, y0 = shapely.get_x(p0), shapely.get_y(p0)
        cross = (shapely.get_x(p1) - x0) * (y[m] - y0) - (shapely.get_y(p1) - y0) * (x[m] - x0)
        chain[m] = c
        side[m] = np.where(cross > 0, "left", "right")
    out = pd.DataFrame({"stage": stage, "chainage_m": chain, "distance_m": dist.min(0), "side": side})
    out.loc[~ok, ["stage", "side"]] = None
    out.loc[~ok, ["chainage_m", "distance_m"]] = np.nan
    return out


def group_heads(assigned, cfg=CFG):
    """(stage, community, window) -> head window. Groups under min_group_ha join the community's nearest upstream
    group on the same stage; if the first surviving group is still small, the next survivor downstream joins it."""
    mn = cfg["offtakes"]["min_group_ha"]
    ha = assigned.groupby(["stage", "community", "window"], sort=True).area_ha.sum()
    head = {}
    for (s, c), g in ha.groupby(level=[0, 1], sort=True):
        survivors = []
        for (_, _, w), h in g.items():
            if h < mn and survivors:
                head[(s, c, w)] = survivors[-1][0]; survivors[-1][1] += h
            else:
                head[(s, c, w)] = w; survivors.append([w, h])
        if len(survivors) > 1 and survivors[0][1] < mn:
            first, nxt = survivors[0][0], survivors[1][0]
            for k, v in list(head.items()):
                if k[:2] == (s, c) and v == nxt:
                    head[k] = first
    return head


# ---------------------------------------------------------------- gates
def partition(ha, cfg=CFG):
    """Split an ordered run of parcel areas into contiguous gates: within [min_ha, max_ha] where possible (a single
    parcel over max_ha stands alone), fewest undersize gates first, then least squared deviation from target_ha.
    Returns (start, end) slices. Deterministic: ties keep the shortest last segment."""
    g = cfg["gates"]
    mn, mx, tg = g["min_ha"], g["max_ha"], g["target_ha"]
    cs = np.concatenate([[0.0], np.cumsum(ha)])
    n = len(ha)
    best = np.full(n + 1, np.inf); best[0] = 0.0
    prev = np.zeros(n + 1, dtype=int)
    for j in range(1, n + 1):
        for i in range(j - 1, -1, -1):
            s = cs[j] - cs[i]
            if s > mx + 1e-9 and j - i > 1:
                break
            cost = UNDERSIZE_PENALTY + (mn - s) ** 2 if s < mn - 1e-9 else (0.0 if s > mx else (s - tg) ** 2)
            if best[i] + cost < best[j] - 1e-12:
                best[j], prev[j] = best[i] + cost, i
    cuts, j = [], n
    while j > 0:
        cuts.append((prev[j], j)); j = prev[j]
    return cuts[::-1]


def gate_order(g, offtake_chain, cfg=CFG):
    """Serpentine order inside one offtake and canal side: 250 m chainage bins, distance up in even bins, down in odd."""
    b = np.floor((g.chainage_m.to_numpy() - offtake_chain) / cfg["gates"]["bin_m"]).astype(int)
    d = np.where(b % 2 == 0, g.distance_m.to_numpy(), -g.distance_m.to_numpy())
    return g.assign(_bin=b, _d=d, _pid=g.index).sort_values(["_bin", "_d", "_pid"], kind="mergesort").index


def gate_id(offtake_id, pids, cfg=CFG):
    return "GT-" + short_hash(offtake_id + "|" + ",".join(sorted(pids)), cfg["gates"]["id_hash_len"])


def size_flag(ha, n, cfg=CFG):
    g = cfg["gates"]
    if ha > g["max_ha"] + 1e-9:
        return "single_parcel_over_max" if n == 1 else "over_max"
    return "under_min" if ha < g["min_ha"] - 1e-9 else "ok"


# ---------------------------------------------------------------- network
def build_network(parcels, lines, terrain, cfg=CFG):
    """parcels: index internal_parcel_id; community, area_ha, ltype, x, y (NaN when unlocated). Pure: no file I/O."""
    a, o, sp = cfg["assignment"], cfg["offtakes"], cfg["spurs"]
    labels = {s: v["label"] for s, v in cfg["canal"]["stages"].items()}
    up = upstream_offsets(lines, cfg)
    p = parcels.sort_index().copy()
    p = p.join(project(p.x, p.y, lines).set_index(p.index))
    p["elev"] = terrain.at(p.x.to_numpy(), p.y.to_numpy())
    reason = pd.Series("", index=p.index, dtype=object)
    reason[p.distance_m.isna()] = "no location"
    reason[(reason == "") & (p.community == "(outside community outlines)")] = "outside community outlines"
    reason[(reason == "") & (p.distance_m > a["max_distance_m"])] = "beyond max distance from canal"
    p["status"] = np.where(reason == "", "assigned", "unassigned")
    p["unassigned_reason"] = reason.replace("", None)
    p["window"] = np.floor(p.chainage_m / o["chainage_window_m"])
    profile = canal_profile(lines, terrain, cfg)

    # offtakes = branch heads
    rows = []
    heads = group_heads(p[p.status == "assigned"], cfg)
    p["window"] = [heads.get((s, c, w), w) for s, c, w in zip(p.stage, p.community, p.window)]
    asg = p[p.status == "assigned"]
    for (stage, comm, win), g in asg.groupby(["stage", "community", "window"], sort=True):
        oid = "OT-" + short_hash(f"{stage}|{comm}|{int(win)}", 8)
        chain = float(np.floor(g.chainage_m.min() / o["round_m"]) * o["round_m"])
        canal_z, basis = canal_elevation(profile, stage, chain, cfg)
        zone_z = float(np.nanmedian(g.elev)) if g.elev.notna().any() else np.nan
        rise = zone_z - canal_z
        pt = lines[stage].interpolate(chain)
        rows.append({"branch": oid, "stage_key": stage, "stage": labels[stage], "community": comm, "window": int(win),
                     "chainage_m": chain, "upstream_m": up[stage], "x": pt.x, "y": pt.y,
                     "canal_elev_m": round(canal_z, 1) if np.isfinite(canal_z) else None,
                     "zone_median_elev_m": round(zone_z, 1) if np.isfinite(zone_z) else None,
                     "rise_m": round(rise, 1) if np.isfinite(rise) else None,
                     "offtake_type": "pump" if np.isfinite(rise) and rise >= o["pump_min_rise_m"] else "gate",
                     "type_rule": "terrain rule" if np.isfinite(rise) else "terrain not covered, default gate",
                     "type_basis": o["type_basis"], "canal_terrain_basis": basis})
    br = pd.DataFrame(rows)
    br = br.sort_values(["stage_key", "chainage_m", "community"], kind="mergesort").reset_index(drop=True)
    br["label"] = br.stage + "-B" + (br.groupby("stage_key").cumcount() + 1).astype(str)
    key = {(r.stage_key, r.community, r.window): r.branch for r in br.itertuples()}
    p["branch"] = [key.get((s, c, w)) if st == "assigned" else None
                   for s, c, w, st in zip(p.stage, p.community, p.window, p.status)]

    # gates
    gates, pg = [], {}
    bmap = br.set_index("branch")
    for oid in br.branch:
        b = bmap.loc[oid]
        k = 0
        for side in ("left", "right"):
            g = p[(p.branch == oid) & (p.side == side)]
            if g.empty:
                continue
            g = g.loc[gate_order(g, b.chainage_m, cfg)]
            for s, e in partition(g.area_ha.to_numpy(), cfg):
                m = g.iloc[s:e]
                k += 1
                gid = gate_id(oid, list(m.index), cfg)
                ha = float(m.area_ha.sum())
                cx, cy = float(np.average(m.x, weights=m.area_ha)), float(np.average(m.y, weights=m.area_ha))
                dist = float(np.hypot(cx - b.x, cy - b.y))
                f = min(1.0, sp["length_cap_m"] / dist) if dist > 0 else 1.0
                row = {"gate": gid, "branch": oid, "branch_label": b.label, "label": f"{b.label}-G{k}", "stage": b.stage,
                       "community": b.community, "side": side, "n_parcels": int(len(m)), "ha": round(ha, 4),
                       "x": cx, "y": cy, "dist_km": round(dist / 1000.0, 3),
                       "spur_x": b.x + (cx - b.x) * f, "spur_y": b.y + (cy - b.y) * f, "spur_truncated": bool(f < 1.0),
                       "size_flag": size_flag(ha, len(m), cfg)}
                for lt in LTYPES:
                    row[f"ha_{lt}"] = round(float(m.area_ha[m.ltype == lt].sum()), 4)
                gates.append(row)
                for pid in m.index:
                    pg[pid] = gid
    gt = pd.DataFrame(gates)
    p["gate"] = p.index.map(pg)

    # branch aggregates
    agg = gt.groupby("branch").agg(n_gates=("gate", "size"), ha=("ha", "sum"), branch_km=("dist_km", "max"),
                                   **{f"ha_{lt}": (f"ha_{lt}", "sum") for lt in LTYPES})
    br = br.join(agg, on="branch")
    br["ha"] = br.ha.round(4)
    br["ha_per_branch_km"] = (br.ha / br.branch_km.clip(lower=o["round_m"] / 1000.0)).round(1)
    br["parent"] = br.stage_key
    br["level"] = 1
    gt["parent"] = gt.branch
    gt["level"] = 2
    return {"branches": br.drop(columns=["window"]), "gates": gt, "parcels": p, "profile": profile}


# ---------------------------------------------------------------- id table
def id_changes(old, new):
    """old/new parcel_gate tables (internal_parcel_id, branch, gate, status). For each kind (branch, gate): every old id
    maps to the new id holding most of its parcels; unchanged / changed / removed; new ids nobody maps to are 'new'."""
    rows = []
    for kind in ("branch", "gate"):
        o = old.loc[old.status == "assigned", ["internal_parcel_id", kind]].rename(columns={kind: "old_id"})
        n = new.loc[new.status == "assigned", ["internal_parcel_id", kind]].rename(columns={kind: "new_id"})
        m = o.merge(n, on="internal_parcel_id", how="left")
        size = o.groupby("old_id").size()
        hits = set()
        for oid, g in m.groupby("old_id", sort=True):
            c = g.new_id.dropna().value_counts()
            if c.empty:
                rows.append({"kind": kind, "old_id": oid, "new_id": None, "status": "removed", "overlap_share": 0.0})
                continue
            top = sorted(c[c == c.max()].index)[0]
            hits.add(top)
            rows.append({"kind": kind, "old_id": oid, "new_id": top, "status": "unchanged" if top == oid else "changed",
                         "overlap_share": round(float(c[top] / size[oid]), 4)})
        for nid in sorted(set(n.new_id.dropna()) - hits):
            rows.append({"kind": kind, "old_id": None, "new_id": nid, "status": "new", "overlap_share": None})
    return pd.DataFrame(rows, columns=["kind", "old_id", "new_id", "status", "overlap_share"])


# ---------------------------------------------------------------- QA
def tree_errors(branches, gates, lines):
    err = []
    nodes = {s: None for s in lines}
    for r in branches.itertuples():
        if r.branch in nodes:
            err.append(f"duplicate node {r.branch}")
        nodes[r.branch] = r.parent
    for r in gates.itertuples():
        if r.gate in nodes:
            err.append(f"duplicate node {r.gate}")
        nodes[r.gate] = r.parent
    for n in nodes:
        seen, cur, depth = {n}, nodes[n], 1
        while cur is not None:
            if cur not in nodes:
                err.append(f"{n}: missing parent {cur}"); break
            if cur in seen:
                err.append(f"{n}: loop"); break
            seen.add(cur); cur = nodes[cur]; depth += 1
        if depth > 3:
            err.append(f"{n}: depth {depth}")
    return err


def upstream_rule_errors(parcels, branches):
    """G2.4: an assigned parcel's offtake is upstream of it and no other offtake of its community lies between."""
    p = parcels[parcels.status == "assigned"].join(branches.set_index("branch")[["chainage_m"]].rename(columns={"chainage_m": "ot_m"}), on="branch")
    bad = int((p.ot_m > p.chainage_m + 1e-6).sum())
    for (s, c), g in p.groupby(["stage", "community"]):
        ots = np.sort(branches[(branches.stage_key == s) & (branches.community == c)].chainage_m.to_numpy())
        k = np.searchsorted(ots, g.chainage_m.to_numpy() + 1e-6, side="right") - 1
        bad += int((ots[np.clip(k, 0, None)] != g.ot_m.to_numpy()).sum())
    return bad


def summarize(net, lines, cfg=CFG):
    br, gt, p, prof = net["branches"], net["gates"], net["parcels"], net["profile"]
    a, q, g = cfg["assignment"], cfg["qa"], cfg["gates"]
    asg = p[p.status == "assigned"]
    ha_u, ha_a = float(p.area_ha.sum()), float(asg.area_ha.sum())
    un = p[p.status == "unassigned"].groupby("unassigned_reason").area_ha.agg(["size", "sum"])
    located = p.distance_m.notna() & (p.community != "(outside community outlines)")
    sens = {str(m): {"parcels_share": round(float((located & (p.distance_m <= m)).mean()), 4),
                     "ha_share": round(float(p.area_ha[located & (p.distance_m <= m)].sum() / ha_u), 4)} for m in a["sensitivity_m"]}
    band = q["ha_per_branch_km_band"]
    tree = tree_errors(br, gt, lines)
    once = int(asg.gate.isna().sum()) + int(p.index.duplicated().sum())
    mixed = int((gt.groupby("gate").size() != 1).sum())
    gate_comm = asg.groupby("gate").agg(nc=("community", "nunique"), ns=("side", "nunique"))
    hs = gt.ha
    checks = {
        "assigned_share_parcels_ge_target": round(len(asg) / len(p), 4) >= a["target_assigned_share"],
        "ha_reconcile_universe": abs(ha_a + float(p.area_ha[p.status == "unassigned"].sum()) - ha_u) <= q["ha_tolerance"],
        "ha_reconcile_gates": abs(float(gt.ha.sum()) - ha_a) <= q["ha_tolerance"],
        "ha_reconcile_branches": abs(float(br.ha.sum()) - ha_a) <= q["ha_tolerance"],
        "each_assigned_parcel_in_one_gate": once == 0 and mixed == 0,
        "tree_valid": not tree,
        "gate_one_community_one_side": bool((gate_comm.nc == 1).all() and (gate_comm.ns == 1).all()),
        "nearest_upstream_offtake_rule": upstream_rule_errors(p, br) == 0,
        "gate_max_size": bool((gt.size_flag != "over_max").all()),
        "canal_falls_downstream": all(v["falls_downstream"] for v in orientation_check(prof, lines).values()),
    }
