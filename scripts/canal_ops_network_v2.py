def id_changes(old, new, kinds=("main", "unit", "outlet")):
    """Old -> new ids per kind by the parcels they serve (same rule as v1)."""
    rows = []
    for kind in kinds:
        o = old.loc[old[kind].notna(), ["internal_parcel_id", kind]].rename(columns={kind: "old_id"})
        n = new.loc[new[kind].notna(), ["internal_parcel_id", kind]].rename(columns={kind: "new_id"})
        m = o.merge(n, on="internal_parcel_id", how="left")
        size = o.groupby("old_id").size()
        hits = set()
        for oid, g in m.groupby("old_id", sort=True):
            c = g.new_id.dropna().value_counts()
            if c.empty:
                rows.append({"kind": kind, "old_id": oid, "new_id": None, "status": "removed", "overlap_share": 0.0}); continue
            top = sorted(c[c == c.max()].index)[0]
            hits.add(top)
            rows.append({"kind": kind, "old_id": oid, "new_id": top, "status": "unchanged" if top == oid else "changed",
                         "overlap_share": round(float(c[top] / size[oid]), 4)})
        for nid in sorted(set(n.new_id.dropna()) - hits):
            rows.append({"kind": kind, "old_id": None, "new_id": nid, "status": "new", "overlap_share": None})
    return pd.DataFrame(rows, columns=["kind", "old_id", "new_id", "status", "overlap_share"])


def id_map_v1(new, cfg=CFG):
    """v1 branch -> v2 main offtake and v1 gate -> v2 unit (tertiary canal or direct outlet), by parcels served."""
    v1 = pd.read_parquet(ROOT / cfg["inputs"]["network_v1_parcels"], columns=["internal_parcel_id", "status", "branch", "gate"])
    lab = pd.read_parquet(ROOT / cfg["inputs"]["network_v1_branches"], columns=["branch", "label"]).set_index("branch").label
    v1 = v1[v1.status == "assigned"]
    m = v1.merge(new[["internal_parcel_id", "main", "unit"]], on="internal_parcel_id", how="left")
    rows = []
    for (k1, k2) in (("branch", "main"), ("gate", "unit")):
        for oid, g in m.groupby(k1, sort=True):
            c = g[k2].dropna().value_counts()
            top = sorted(c[c == c.max()].index)[0] if len(c) else None
            rows.append({"kind": f"v1 {k1} -> v2 {'main offtake' if k2 == 'main' else 'tertiary unit or direct outlet'}",
                         "v1_id": oid, "v1_label": lab.get(oid) if k1 == "branch" else None, "v2_id": top,
                         "overlap_share": round(float(c.max() / len(g)), 4) if len(c) else 0.0, "v1_parcels": int(len(g))})
    return pd.DataFrame(rows)


def ledger_constraints(cfg=CFG, guard=None):
    """Standing constraints in the real ledger that name v1 ids: flagged for review against the v2 id table."""
    import re
    path = ROOT / cfg["inputs"]["ledger"]
    if guard is not None:
        guard.record(path, "sqlite")
    if not path.exists():
        return {"events": 0, "constraints": 0, "flagged": []}
    con = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True)
    try:
        ev = con.execute("select id, kind, payload from events").fetchall()
    finally:
        con.close()
    pat = re.compile(r"\b(?:I|II)-B\d+(?:-G\d+)?\b|\b(?:OT|GT)-[0-9a-f]{8,10}\b")
    flagged = [{"event": i, "kind": k, "v1_ids": sorted(set(pat.findall(pl or "")))[:20]} for i, k, pl in ev
               if "constraint" in (k or "") or "standing" in (k or "")]
    return {"events": len(ev), "constraints": len(flagged), "flagged": [f for f in flagged if f["v1_ids"]],
            "note": "v1 ids in standing constraints are flagged; map them with id_map_v1_to_v2.parquet before reuse"}


