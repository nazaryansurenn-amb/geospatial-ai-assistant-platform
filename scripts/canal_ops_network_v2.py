def attach_communities(x, y, comm, cfg=CFG):
    """(names, basis) for points without a community: containing outline, else nearest within the limit, else outside."""
    lim = cfg["locations"]["community_attach_max_m"]
    pts = shapely.points(x, y)
    names = np.full(len(pts), OUTSIDE, dtype=object)
    basis = np.full(len(pts), "outside community outlines", dtype=object)
    dist = np.vstack([shapely.distance(pts, g) for g in comm.geometry.values])
    k = dist.argmin(0)
    best = dist.min(0)
    inside = best <= 0
    near = (best > 0) & (best <= lim)
    names[inside | near] = comm.name_hy.to_numpy()[k[inside | near]]
    basis[inside] = "community outline contains the point"
    basis[near] = f"nearest community outline within {lim} m"
    return names, basis


def load_parcels(cfg=CFG):
    """All 22,802 observed-zone parcels with class, farm flag, community, metric point and location source."""
    import geopandas as gpd
    from pyproj import Transformer
    lt = cfg["land_types"]
    d = pd.read_parquet(ROOT / cfg["inputs"]["land_types"],
                        columns=["internal_parcel_id", "item_id", "community", "area_ha", "lon", "lat", "type6"])
    d["cls"] = d.type6.fillna("NOT_CLASSIFIABLE")
    d["farm"] = d.cls.isin(lt["farm_classes"])
    d["ltype"] = d.cls.map(lt["ltype"])
    miss = d.lon.isna() | d.lat.isna()
    if miss.any():
        ids = pd.read_parquet(ROOT / cfg["inputs"]["parcel_ids"], columns=["internal_parcel_id", "cadastre_code"])
        cad = gpd.read_file(ROOT / cfg["inputs"]["cadastre"], columns=["cadastre_code"])
        cad = cad.merge(ids, on="cadastre_code", how="inner").set_index("internal_parcel_id")
        rep = shapely.point_on_surface(cad.geometry.reindex(d.loc[miss, "internal_parcel_id"]).values)
        d.loc[miss, "lon"], d.loc[miss, "lat"] = shapely.get_x(rep), shapely.get_y(rep)
    d["loc_source"] = np.where(miss, "cadastral geometry (representative point)", "land types v1.5")
    x, y = Transformer.from_crs("EPSG:4326", cfg["crs"], always_xy=True).transform(d.lon.to_numpy(), d.lat.to_numpy())
    d["x"], d["y"] = x, y
    d["community_basis"] = np.where(d.community.notna(), "land types v1.5", None)
    nc = d.community.isna().to_numpy()
    if nc.any():
        names, basis = attach_communities(x[nc], y[nc], load_communities(cfg), cfg)
        d.loc[nc, "community"], d.loc[nc, "community_basis"] = names, basis
    return d.drop(columns=["type6"]).set_index("internal_parcel_id").sort_index()


def gross_series(pids, ltype, cfg=CFG):
    """(parcels x 96 dekads) gross m3 at the field from the 2021-2024 demand reference, and the days of each dekad."""
    s = cfg["sizing"]
    eff = json.loads((ROOT / cfg["inputs"]["sim_config"]).read_text(encoding="utf-8"))["water_chain"]["field_efficiency"]
    r = pd.read_parquet(ROOT / cfg["inputs"]["demand_reference"], columns=["pid", "year", "dekad_id", "days", s["need_column"]])
    r = r[r.year <= 2024]
    r["col"] = r.year.astype(str) + "|" + r.dekad_id.astype(str)
    days = r.groupby("col").days.first().sort_index()
    m = r.pivot_table(index="pid", columns="col", values=s["need_column"], aggfunc="sum").reindex(index=pids, columns=days.index)
    e = pd.Series(ltype, index=pids).map(lambda t: 0.0 if t == "greenhouse" or t is None else 1.0 / eff.get(t, eff["field"]))
    return m.fillna(0.0).to_numpy() * e.to_numpy()[:, None], days.to_numpy(dtype=float)


# ---------------------------------------------------------------- canal level
def canal_levels(lines, terrain, cfg=CFG):
    """Canal terrain profile made non-increasing downstream; stage II starts at most at the end of stage I."""
    prof = n1.canal_profile(lines, terrain, canal_cfg(cfg))
    out, cap, end_level = [], np.inf, np.inf
    for stage, s in cfg["main_canal"]["stages"].items():
        p = prof[prof.stage == stage].sort_values("chainage_m").copy()
        if s.get("draws_through"):
            cap = min(cap, end_level)
        p["level"] = np.minimum(p.elev.cummin(), cap)          # NaN stays NaN where terrain is not covered
        end_level = float(p.level.dropna().iloc[-1]) if p.level.notna().any() else np.inf
        out.append(p)
    return pd.concat(out, ignore_index=True)


def level_at(levels, stage, chainage, window=250.0):
    p = levels[(levels.stage == stage) & levels.level.notna()]
    if p.empty:
        return np.nan
    k = (p.chainage_m - chainage).abs()
    if k.min() > window:
        return np.nan
    return float(np.interp(chainage, p.chainage_m.to_numpy(), p.level.to_numpy()))


# ---------------------------------------------------------------- blocks and outlets
def secondary_blocks(p, cfg=CFG):
    """Block key per farm parcel: (stage, side, head window); small groups join a neighbour on the same stage/side."""
    b = cfg["secondary_blocks"]
    mn = b["min_ha"]
    win = np.floor(p.chainage_m.to_numpy() / b["chainage_window_m"]).astype(int)
    ha = p.area_ha.groupby([p.stage.to_numpy(), p.side.to_numpy(), win]).sum()
    gap = b["max_merge_gap_windows"]
    head = {}
    for (s, sd), g in ha.groupby(level=[0, 1], sort=True):
        surv = []                                               # [head window, ha, last window]
        for (_, _, w), h in g.items():
            if h < mn and surv and w - surv[-1][2] <= gap:
                head[(s, sd, w)] = surv[-1][0]
                surv[-1][1] += h
                surv[-1][2] = w
            else:
                head[(s, sd, w)] = w
                surv.append([w, h, w])
        for i in range(len(surv) - 1):                          # a small group with no upstream partner takes the next one
            alone = i == 0 or surv[i][0] - surv[i - 1][2] > gap
            if surv[i][1] < mn and alone and surv[i + 1][0] - surv[i][2] <= gap:
                first, nxt = surv[i][0], surv[i + 1][0]
                for k, v in list(head.items()):
                    if k[:2] == (s, sd) and v == nxt:
                        head[k] = first
                surv[i + 1][0], surv[i + 1][1] = first, surv[i + 1][1] + surv[i][1]
    return pd.Series([f"{s}|{sd}|{head[(s, sd, w)]:03d}" for s, sd, w in zip(p.stage, p.side, win)], index=p.index)


def outlets_of(p, cfg=CFG):
    """Parcel groups inside one block: one grid cell and one community; area-weighted point."""
    c = cfg["outlets"]["cell_m"]
    key = (np.floor(p.x / c).astype(int).astype(str) + "_" + np.floor(p.y / c).astype(int).astype(str) + "|" + p.community)
    g = p.assign(_k=key.to_numpy(), _wx=p.x * p.area_ha, _wy=p.y * p.area_ha).groupby("_k", sort=True)
    o = g.agg(ha=("area_ha", "sum"), wx=("_wx", "sum"), wy=("_wy", "sum"), community=("community", "first"), n=("area_ha", "size"))
    o["x"], o["y"] = o.wx / o.ha, o.wy / o.ha
    return o.drop(columns=["wx", "wy"]), pd.Series(key.to_numpy(), index=p.index)


# ---------------------------------------------------------------- tree
def forbidden(xy, barriers, tol=0.5):
    """n x n mask of point pairs whose straight segment crosses a barrier line away from the segment's end points."""
    n = len(xy)
    bad = np.zeros((n, n), dtype=bool)
    if n < 2 or not len(barriers):
        return bad
    i, j = np.triu_indices(n, 1)
    seg = shapely.linestrings(np.stack([xy[i], xy[j]], axis=1))
    a, b = shapely.STRtree(barriers).query(seg, predicate="intersects")
    if len(a):
        x = shapely.intersection(seg[a], barriers[b])
        hit = np.unique(a[far_hits(x, [shapely.points(xy[i[a]]), shapely.points(xy[j[a]])], tol)])
        bad[i[hit], j[hit]] = True
        bad[j[hit], i[hit]] = True
    return bad


def far_hits(x, ends, tol=0.5):
    """x: intersection geometries; ends: point arrays of the same length. True where ANY part of the intersection lies
    more than tol from every end point (touching at an end point while crossing elsewhere still counts as crossing),
    or where the lines overlap along more than tol."""
    x = np.asarray(x, dtype=object)
    far = np.zeros(len(x), dtype=bool)
    if not len(x):
        return far
    parts, idx = shapely.get_parts(x, return_index=True)
    if not len(parts):
        return far
    d = np.min([shapely.distance(parts, np.asarray(e, dtype=object)[idx]) for e in ends], axis=0)
    line = np.isin(shapely.get_type_id(parts), [1, 2, 5]) & (shapely.length(parts) > tol)
    np.logical_or.at(far, idx, (d > tol) | line)
    return far


def _rep(pt, k):
    return np.full(k, shapely.points(np.asarray(pt, dtype=float)), dtype=object)


def crosses_any(a, b, segs, tol=0.5):
    """Does segment a-b cross one of segs (point pairs) away from the end points of either?"""
    if not segs:
        return False
    s = shapely.linestrings([a, b])
    arr = shapely.linestrings([[p, q] for p, q in segs])
    hit = np.flatnonzero(shapely.intersects(arr, s))
    if not len(hit):
        return False
    ends = [_rep(a, len(hit)), _rep(b, len(hit)), shapely.points(np.asarray([segs[k][0] for k in hit], dtype=float)),
            shapely.points(np.asarray([segs[k][1] for k in hit], dtype=float))]
    return bool(far_hits(shapely.intersection(arr[hit], s), ends, tol).any())


def crosses_lines(a, b, lines, tol=0.5):
    """Does segment a-b cross one of the barrier lines anywhere but at a-b's own end points?"""
    if not len(lines):
        return False
    s = shapely.linestrings([a, b])
    arr = np.asarray(list(lines), dtype=object)
    hit = np.flatnonzero(shapely.intersects(arr, s))
    if not len(hit):
        return False
    return bool(far_hits(shapely.intersection(arr[hit], s), [_rep(a, len(hit)), _rep(b, len(hit))], tol).any())


def emst(xy, bad=None):
    """Exact Euclidean minimum spanning tree by Prim from node 0 that never uses a forbidden pair while another way
    exists. Returns (parent[], forced_crossings); parent[0] = -1. Deterministic."""
    n = len(xy)
    parent = np.full(n, -1)
    if n < 2:
        return parent, 0
    bad = np.zeros((n, n), dtype=bool) if bad is None else bad
    done = np.zeros(n, dtype=bool)
    done[0] = True
    raw = np.hypot(xy[:, 0] - xy[0, 0], xy[:, 1] - xy[0, 1])
    best = np.where(bad[0], np.inf, raw)
    fall = raw.copy()                                           # cheapest link of any kind, used only if nothing else
    frm, ffrm = np.zeros(n, dtype=int), np.zeros(n, dtype=int)
    forced = 0
    tree = []                                                   # edges so far: a new edge may not cross them
    for _ in range(n - 1):
        while True:
            cand = np.where(done, np.inf, best)
            j = int(np.argmin(cand))
            if not np.isfinite(cand[j]) or not crosses_any(xy[frm[j]], xy[j], tree):
                break
            bad[frm[j], j] = bad[j, frm[j]] = True              # crosses the block's own tree: next best link
            d = np.where(done & ~bad[j], np.hypot(xy[:, 0] - xy[j, 0], xy[:, 1] - xy[j, 1]), np.inf)
            best[j], frm[j] = float(d.min()), int(np.argmin(d))
        if np.isfinite(cand[j]):
            parent[j] = frm[j]
        else:
            j = int(np.argmin(np.where(done, np.inf, fall)))
            parent[j] = ffrm[j]
            forced += 1
        done[j] = True
        tree.append((xy[parent[j]], xy[j]))
        d = np.hypot(xy[:, 0] - xy[j, 0], xy[:, 1] - xy[j, 1])
        upd = ~done & ~bad[j] & (d < best - 1e-9)
        best[upd], frm[upd] = d[upd], j
        updf = ~done & (d < fall - 1e-9)
        fall[updf], ffrm[updf] = d[updf], j
    return parent, forced


def children_of(parent, xy):
    ch = [[] for _ in range(len(parent))]
    for v in range(1, len(parent)):
        ch[parent[v]].append(v)
    for u, c in enumerate(ch):
        c.sort(key=lambda v: (math.atan2(xy[v, 1] - xy[u, 1], xy[v, 0] - xy[u, 0]), v))
    return ch


def postorder(ch):
    out, stack = [], [(0, False)]
    while stack:
        v, seen = stack.pop()
        if seen:
            out.append(v)
        else:
            stack.append((v, True))
            stack.extend((c, False) for c in reversed(ch[v]))
    return out


def cut_tree(parent, ha, xy, cfg=CFG):
    """Split a rooted tree (node 0 = main gate) into tertiary units and the secondary canal.

    Returns (units, on_secondary): units are {"kind": "tertiary", "at": secondary node, "first": [first nodes],
    "members": [...]} or {"kind": "direct", "node": v}; on_secondary is the connected set of secondary nodes (incl. 0).
    Every non-root node ends in exactly one unit."""
    t = cfg["tree"]
    lo, hi = t["tertiary_cut_min_ha"], t["tertiary_max_ha"]
    ch = children_of(parent, xy)
    state, acc, mem = [None] * len(parent), np.zeros(len(parent)), [None] * len(parent)
    units, on_sec = [], set()
    long_link = t["long_link_m"]
    for v in postorder(ch):
        open_ch = [c for c in ch[v] if state[c] == "open"]
        closed = any(state[c] in ("cut", "sec") for c in ch[v])
        far = v != 0 and float(np.hypot(*(xy[v] - xy[parent[v]]))) > long_link   # a long link is secondary canal
        if v != 0 and not closed and not far and ha[v] <= hi:
            tot = ha[v] + sum(acc[c] for c in open_ch)
            members = [v] + [m for c in open_ch for m in mem[c]]
            if tot < lo:
                state[v], acc[v], mem[v] = "open", tot, members
                continue
            if tot <= hi:
                state[v] = "cut"
                units.append({"kind": "tertiary", "at": int(parent[v]), "first": [v], "members": members, "ha": tot})
                continue
        state[v] = "sec"
        on_sec.add(v)
        runs, run = [], []                                      # open children between two secondary branches
        for c in ch[v]:
            if state[c] == "open":
                run.append(c)
            elif run:
                runs.append(run)
                run = []
        if run:
            runs.append(run)
        bins = []
        for run in runs:
            rb, cur, cur_ha = [], [], 0.0
            for c in run:
                if cur and cur_ha + acc[c] > hi:
                    rb.append([cur, cur_ha]); cur, cur_ha = [], 0.0
                cur.append(c); cur_ha += acc[c]
                if cur_ha >= lo:
                    rb.append([cur, cur_ha]); cur, cur_ha = [], 0.0
            if cur:
                if rb and rb[-1][1] + cur_ha <= hi:
                    rb[-1][0] += cur; rb[-1][1] += cur_ha
                else:
                    rb.append([cur, cur_ha])
            bins += rb
        tert = []
        for b, h in bins:
            if h < lo and all(len(mem[c]) == 1 for c in b):
                for c in b:                                     # single adjacent parcel groups: direct outlets
                    state[c] = "sec"; on_sec.add(c)
                    units.append({"kind": "direct", "node": c})
            else:
                tert.append({"kind": "tertiary", "at": v, "first": list(b), "members": [m for c in b for m in mem[c]], "ha": h})
        if v != 0:                                              # the node's own parcels join the smallest tertiary here
            here = tert + [u for u in units if u["kind"] == "tertiary" and u["at"] == v and "own" not in u]
            fit = [u for u in here if u["ha"] + ha[v] <= hi]
            if fit and ha[v] <= hi:
                u = min(fit, key=lambda u: (u["ha"], u["first"][0]))
                u["members"].insert(0, v)
                u["ha"] += ha[v]
                u["own"] = v
            else:
                units.append({"kind": "direct", "node": v})
        units += tert
    on_sec.add(0)
    return units, on_sec


def path_lengths(parent, xy):
    d = np.zeros(len(parent))
    order = postorder(children_of(parent, xy))[::-1]          # root first
    for v in order:
        if parent[v] >= 0:
            d[v] = d[parent[v]] + float(np.hypot(*(xy[v] - xy[parent[v]])))
    return d


def toward(a, b, dist):
    v = b - a
    n = float(np.hypot(*v))
    if n == 0:
        return a.copy()
    return a + v * min(dist, 0.4 * n) / n


def wmedian(v, w):
    v, w = np.asarray(v, float), np.asarray(w, float)
    ok = np.isfinite(v) & (w > 0)
    if not ok.any():
        return np.nan
    v, w = v[ok], w[ok]
    o = np.argsort(v, kind="mergesort")
    c = np.cumsum(w[o])
    return float(v[o][np.searchsorted(c, 0.5 * c[-1])])


def terrain_state(d_med, band):
    if not np.isfinite(d_med):
        return "terrain not covered"
    if d_med > band:
        return "pumping"
    if d_med < -band:
        return "gravity"
    return "terrain uncertain"


# ---------------------------------------------------------------- one secondary block
def build_block(bp, line, root_level, cfg=CFG, barriers=None):
    """bp: farm parcels of one block (x, y, area_ha, community, elev); barriers: lines its canals must not cross (the
    main canal and canals of blocks built earlier). Returns the block's local structure."""
    t, tr = cfg["tree"], cfg["terrain"]
    band, gdrop, kdrop = tr["uncertain_band_m"], tr["drop_per_gate_m"], tr["drop_per_km_ditch_m"]
    o, okey = outlets_of(bp, cfg)
    pts = shapely.points(o.x.to_numpy(), o.y.to_numpy())
    near = int(np.argmin(shapely.distance(pts, line)))
    rch = float(shapely.line_locate_point(line, pts[near]))
    rp = line.interpolate(rch)
    xy = np.vstack([[rp.x, rp.y], o[["x", "y"]].to_numpy()])
    ha = np.concatenate([[0.0], o.ha.to_numpy()])
    bars = np.asarray(list(barriers) if barriers is not None else [line], dtype=object)
    parent, forced_x = emst(xy, forbidden(xy, bars))
    units, on_sec = cut_tree(parent, ha, xy, cfg)
    plen = path_lengths(parent, xy)
    keys = np.concatenate([[None], o.index.to_numpy()])
    # parcel terrain against the water level at the outlet that serves it
    elev_by_outlet = {k: g for k, g in bp.assign(_o=okey).groupby("_o")}
    sec_level = root_level - gdrop - kdrop * plen / 1000.0     # along the secondary (gravity)
    for u in units:
        if u["kind"] == "direct":
            v = u["node"]
            u["pos"], u["path_m"] = xy[v].copy(), plen[v]
            u["outlets"] = {v: 0.0}
            u["edges"] = []
            lv = {v: sec_level[v] - gdrop}
        else:
            at = u["at"]
            g = toward(xy[at], xy[u["first"][0]], t["gate_offset_m"])
            u["pos"], u["path_m"] = g, plen[at] + float(np.hypot(*(g - xy[at])))
            tl = {}
            for m in u["members"]:                              # path inside the tertiary from its secondary node
                tl[m] = 0.0 if m == u.get("own") else (float(np.hypot(*(xy[m] - xy[at]))) if m in u["first"] else None)
            for m in sorted(u["members"], key=lambda m: plen[m]):
                if tl[m] is None:
                    tl[m] = tl[parent[m]] + float(np.hypot(*(xy[m] - xy[parent[m]])))
            u["outlets"] = tl
            u["edges"] = [(xy[at], xy[m]) for m in u["first"]] + [(xy[parent[m]], xy[m]) for m in u["members"]
                                                                   if m not in u["first"] and m != u.get("own")]
            head = root_level - gdrop - kdrop * u["path_m"] / 1000.0 - gdrop
            lv = {m: head - kdrop * tl[m] / 1000.0 - gdrop for m in u["members"]}
        dv, wv = [], []
        for m in u["outlets"]:
            pp = elev_by_outlet[keys[m]]
            dv.append(pp.elev.to_numpy() - lv[m]); wv.append(pp.area_ha.to_numpy())
        u["d_med"] = wmedian(np.concatenate(dv), np.concatenate(wv))
        u["state"] = terrain_state(u["d_med"], band)
    # main pump: does the secondary start above the canal?
    head_nodes = [v for v in range(1, len(xy)) if plen[v] <= tr["main_pump_head_m"]] or [int(np.argmin(np.where(np.arange(len(xy)) == 0, np.inf, plen)))]
    hd = pd.concat([elev_by_outlet[keys[v]].assign(_lv=sec_level[v] - gdrop) for v in head_nodes])
    head_d = wmedian(hd.elev - hd._lv, hd.area_ha)
    sec_edges = [(xy[parent[w]], xy[w]) for w in sorted(on_sec) if w != 0]
    tail = max(on_sec, key=lambda v: (plen[v], -v))
    if tail == 0 and units:
        tail_pos = max((u["pos"] for u in units), key=lambda q: float(np.hypot(*(q - xy[0]))))
        tail_from = xy[0]
    else:
        tail_pos, tail_from = xy[tail], xy[parent[tail]] if tail else xy[0]
    step = (tail_pos - tail_from) / max(float(np.hypot(*(tail_pos - tail_from))), 1e-9)
    tert_edges = [e for u in units if u["kind"] == "tertiary" for e in u["edges"]]
    others = list(shapely.linestrings([[a, z] for a, z in sec_edges + tert_edges])) if sec_edges or tert_edges else []
    for off in (t["escape_offset_m"], 10.0, 2.0):               # escape just beyond the tail, never across a canal
        esc = tail_pos + step * off
        if not crosses_lines(tail_pos, esc, others + list(bars)):
            break
    sec_edges.append((tail_pos, esc))
    return {"outlets": o, "outlet_key": okey, "members_by_key": {k: g.index for k, g in okey.groupby(okey)}, "xy": xy, "keys": keys, "parent": parent, "plen": plen, "units": units,
            "on_sec": on_sec, "forced_crossings": forced_x, "root_chain": rch, "root_xy": xy[0], "head_state": terrain_state(head_d, band),
            "sec_edges": sec_edges, "escape": esc}


