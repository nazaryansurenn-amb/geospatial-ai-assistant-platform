def to_wgs(x, y, cfg=CFG):
    return n1.to_wgs(x, y, {"crs": cfg["crs"]})


def network_geojson(nd, ed, lines, cfg=CFG):
    feats = []
    for stage, line in lines.items():
        xy = np.asarray(line.coords)
        lon, lat = to_wgs(xy[:, 0], xy[:, 1], cfg)
        lab = cfg["main_canal"]["stages"][stage]["label"]
        feats.append({"type": "Feature", "properties": {"kind": "main_canal", "node": lab, "stage": lab, "basis": "real main canal line"},
                      "geometry": {"type": "LineString", "coordinates": np.column_stack([lon, lat]).tolist()}})
    lon0, lat0 = to_wgs(ed.x0, ed.y0, cfg)
    lon1, lat1 = to_wgs(ed.x1, ed.y1, cfg)
    e = ed.assign(lon0=lon0, lat0=lat0, lon1=lon1, lat1=lat1)
    for (canal, tier), g in e.groupby(["canal", "tier"], sort=True):
        feats.append({"type": "Feature", "properties": {"kind": f"{tier}_canal", "node": canal, "synthetic": True},
                      "geometry": {"type": "MultiLineString", "coordinates": [[[a, b], [c, d]] for a, b, c, d in
                                                                             zip(g.lon0, g.lat0, g.lon1, g.lat1)]}})
    pts = nd[~nd.kind.isin(["main_canal", "secondary_canal", "tertiary_canal"])]
    lon, lat = to_wgs(pts.x, pts.y, cfg)
    for r, x, y in zip(pts.itertuples(), lon, lat):
        props = {"kind": r.kind, "node": r.node, "label": r.label, "community": r.community, "ha": round(float(r.ha), 2),
                 "terrain_state": r.terrain_state if isinstance(r.terrain_state, str) else None,
                 "capacity_lps": None if pd.isna(r.capacity_lps) else float(r.capacity_lps), "pump": bool(r.pump), "synthetic": True}
        feats.append({"type": "Feature", "properties": props, "geometry": {"type": "Point", "coordinates": [float(x), float(y)]}})
    return {"type": "FeatureCollection", "name": cfg["version"], "label": cfg["labels"]["network"], "zone": cfg["labels"]["zone"],
            "features": feats}


