def build_all(cfg=CFG, guard=None):
    """Load inputs, build, size, aggregate. Returns the network dict (no outputs written)."""
    lines = load_canal(cfg)
    parcels = load_parcels(cfg)
    net = build_network(parcels, lines, load_terrain(cfg), cfg)
    reached = net["parcels"][net["parcels"].status == "reached"]
    series, days = gross_series(reached.index, reached.ltype.to_numpy(), cfg)
    nd = size_network(net, series, days, cfg)
    nd = node_aggregates(nd, net["parcels"], cfg)
    nd = add_pumps(nd, cfg, cfg["pumps"]["override"])
    nd = section_of(nd, cfg)
    nd["lon"], nd["lat"] = to_wgs(nd.x, nd.y, cfg)
    net["nodes"] = nd
    net["lines"] = lines
    return net


def build(out=OUT, cfg=CFG):
    out = Path(out)
    with ReadGuard() as guard:
        net = build_all(cfg, guard)
        prev = out / "parcel_node.parquet"
        old = pd.read_parquet(prev) if prev.exists() else None
        idmap = id_map_v1(net["parcels"].reset_index(), cfg)
        constraints = ledger_constraints(cfg, guard)
    out.mkdir(parents=True, exist_ok=True)
    nd, ed, p, lines = net["nodes"], net["edges"].copy(), net["parcels"].reset_index(), net["lines"]
    for c in ("chainage_m", "distance_m", "elev"):
        p[c] = p[c].round(1)
    p = p[PARCEL_COLS]
    ed["lon0"], ed["lat0"] = to_wgs(ed.x0, ed.y0, cfg)
    ed["lon1"], ed["lat1"] = to_wgs(ed.x1, ed.y1, cfg)
    ed["length_m"] = np.hypot(ed.x1 - ed.x0, ed.y1 - ed.y0).round(1)
    changes = id_changes(old if old is not None else p.iloc[:0], p)
    summary = summarize(net, lines, cfg)
    nd[NODE_COLS].to_parquet(out / "nodes.parquet", index=False)
    ed[["canal", "tier", "lon0", "lat0", "lon1", "lat1", "length_m"]].to_parquet(out / "edges.parquet", index=False)
    p.to_parquet(out / "parcel_node.parquet", index=False)
    idmap.to_parquet(out / "id_map_v1_to_v2.parquet", index=False)
    changes.to_parquet(out / "id_changes.parquet", index=False)
    write_json(out / "network.geojson", network_geojson(nd, ed, lines, cfg))
    summary["id_changes"] = {f"{k}_{s}": int(v) for (k, s), v in changes.groupby(["kind", "status"]).size().items()}
    summary["id_map_v1"] = {k: int(v) for k, v in idmap.kind.value_counts().items()}
    summary["ledger_constraints"] = constraints
    summary["read_guard"] = {"violations": guard.violations, "files_read": len(guard.files)}
    write_json(out / "summary.json", summary)
    write_json(out / "manifest.json", {
        "version": cfg["version"], "script": "scripts/canal_ops_network_v2.py", "script_sha256": sha(Path(__file__)),
        "helpers": {"scripts/canal_ops_network_v1.py": sha(ROOT / "scripts/canal_ops_network_v1.py"),
                    "wp_core/read_guard.py": sha(ROOT / "wp_core/read_guard.py")},
        "config": "config/canal_ops_network_v2.json", "config_sha256": sha(CFG_PATH),
        "inputs": {k: sha(ROOT / v) for k, v in cfg["inputs"].items() if k != "not_used" and (ROOT / v).exists()},
        "outputs": {f.name: sha(f) for f in sorted(out.iterdir()) if f.name != "manifest.json"},
        "internal_only": ["parcel_node.parquet", "id_changes.parquet", "id_map_v1_to_v2.parquet"],
        "files_read": guard.files, "read_guard_violations": guard.violations,
        "not_used": cfg["inputs"]["not_used"]})
    return summary


