def pump_units(cap, cfg=CFG):
    p = cfg["pumps"]
    for u in p["unit_lps"]:
        k = math.ceil(cap / u - 1e-9)
        if k <= p["max_units"]:
            return max(k, 1), u
    u = p["unit_lps"][-1]
    return math.ceil(cap / u), u


def build_network(parcels, lines, terrain, cfg=CFG):
    """parcels: load_parcels() frame. Pure: no file I/O. Returns nodes, edges, parcel table and QA inputs."""
    st_lab = {s: v["label"] for s, v in cfg["main_canal"]["stages"].items()}
    up = n1.upstream_offsets(lines, canal_cfg(cfg))
    levels = canal_levels(lines, terrain, cfg)
    p = parcels.sort_index().copy()                             # input order never changes the result
    pr = n1.project(p.x.to_numpy(), p.y.to_numpy(), lines)
    pr.index = p.index
    p = p.join(pr)
    p["elev"] = terrain.at(p.x.to_numpy(), p.y.to_numpy())
    farm = p[p.farm].copy()
    farm["block"] = secondary_blocks(farm, cfg)
    blocks = {}
    bars = [lines[s] for s in lines]
    for key, bp in farm.groupby("block", sort=True):
        stage = key.split("|")[0]
        o_tmp, _ = outlets_of(bp, cfg)
        pts = shapely.points(o_tmp.x.to_numpy(), o_tmp.y.to_numpy())
        rch = float(shapely.line_locate_point(lines[stage], pts[int(np.argmin(shapely.distance(pts, lines[stage])))]))
        rl = level_at(levels, stage, rch)
        blocks[key] = build_block(bp, lines[stage], rl, cfg, bars)
        b = blocks[key]
        built = b["sec_edges"] + [e for u in b["units"] if u["kind"] == "tertiary" for e in u["edges"]]
        bars = bars + list(shapely.linestrings([[a, z] for a, z in built]))
        blocks[key]["stage"] = stage
        blocks[key]["root_level"] = rl
    return assemble(p, farm, blocks, lines, levels, up, st_lab, cfg)


def assemble(p, farm, blocks, lines, levels, up, st_lab, cfg=CFG):
    nodes, edges = [], []
    band = cfg["terrain"]["uncertain_band_m"]
    p["status"] = np.where(p.farm, "reached", "not served: " + p.cls.map(cfg["land_types"]["not_served"]).fillna("other"))
    p["canal_demand"] = np.where(~p.farm, "none (not served)",
                                 np.where(p.cls.isin(list(cfg["land_types"]["zero_canal_demand"])),
                                          p.cls.map(cfg["land_types"]["zero_canal_demand"]), "canal demand"))
    for c in ("main", "secondary", "unit", "outlet", "terrain_state"):
        p[c] = None
    # main offtake numbering per stage in chainage order
    order = sorted(blocks, key=lambda k: (list(st_lab).index(blocks[k]["stage"]), blocks[k]["root_chain"], k))
    count = {s: 0 for s in st_lab}
    for key in order:
        b = blocks[key]
        s = b["stage"]
        count[s] += 1
        main_kind = "main_pump" if b["head_state"] == "pumping" else "main_gate"
        mid = f"{st_lab[s]}-{'P' if main_kind == 'main_pump' else 'G'}{count[s]:02d}"
        sid = f"{mid}-S1"
        b["main_id"], b["sec_id"] = mid, sid
        nodes.append({"node": mid, "kind": main_kind, "level": 1, "parent": st_lab[s], "stage": st_lab[s],
                      "x": b["root_xy"][0], "y": b["root_xy"][1], "chainage_m": round(b["root_chain"], 1),
                      "path_m": 0.0, "terrain_state": b["head_state"], "block": key})
        nodes.append({"node": sid, "kind": "secondary_canal", "level": 1, "parent": mid, "stage": st_lab[s],
                      "x": b["root_xy"][0], "y": b["root_xy"][1], "path_m": 0.0, "block": key})
        for a, z in b["sec_edges"]:
            edges.append({"canal": sid, "tier": "secondary", "x0": a[0], "y0": a[1], "x1": z[0], "y1": z[1]})
        nodes.append({"node": f"{sid}-E", "kind": "tail_escape", "level": 2, "parent": sid, "stage": st_lab[s],
                      "x": b["escape"][0], "y": b["escape"][1], "block": key})
        # units numbered by distance along the secondary
        tu = sorted([u for u in b["units"] if u["kind"] == "tertiary"], key=lambda u: (u["path_m"], u["first"][0]))
        du = sorted([u for u in b["units"] if u["kind"] == "direct"], key=lambda u: (u["path_m"], u["node"]))
        lifted = main_kind == "main_pump"
        for k, u in enumerate(tu, 1):
            pump = (not lifted) and u["state"] == "pumping"
            gid = f"{sid}-{'P' if pump else 'G'}{k}"
            tid = f"{gid}-T1"
            state = "pumping" if lifted else u["state"]
            u["gate_id"], u["unit_id"] = gid, tid
            nodes.append({"node": gid, "kind": "secondary_pump" if pump else "secondary_gate", "level": 2, "parent": sid,
                          "stage": st_lab[s], "x": u["pos"][0], "y": u["pos"][1], "path_m": round(u["path_m"], 1),
                          "terrain_state": state, "block": key})
            nodes.append({"node": tid, "kind": "tertiary_canal", "level": 2, "parent": gid, "stage": st_lab[s],
                          "x": u["pos"][0], "y": u["pos"][1], "path_m": 0.0, "terrain_state": state, "block": key})
            for a, z in u["edges"]:
                edges.append({"canal": tid, "tier": "tertiary", "x0": a[0], "y0": a[1], "x1": z[0], "y1": z[1]})
            for j, m in enumerate(sorted(u["members"], key=lambda m: (u["outlets"][m], m)), 1):
                oid = f"{tid}-G{j}"
                nodes.append({"node": oid, "kind": "tertiary_gate", "level": 3, "parent": tid, "stage": st_lab[s],
                              "x": b["xy"][m][0], "y": b["xy"][m][1], "path_m": round(u["outlets"][m], 1),
                              "terrain_state": state, "block": key})
                p.loc[b["members_by_key"][b["keys"][m]], ["main", "secondary", "unit", "outlet", "terrain_state"]] = [mid, sid, tid, oid, state]
        for k, u in enumerate(du, 1):
            m = u["node"]
            oid = f"{sid}-D{k}"
            state = "pumping" if lifted else u["state"]
            nodes.append({"node": oid, "kind": "direct_outlet", "level": 2, "parent": sid, "stage": st_lab[s],
                          "x": b["xy"][m][0], "y": b["xy"][m][1], "path_m": round(u["path_m"], 1),
                          "terrain_state": state, "pump": bool(state == "pumping" and not lifted), "block": key})
            p.loc[b["members_by_key"][b["keys"][m]], ["main", "secondary", "unit", "outlet", "terrain_state"]] = [mid, sid, oid, oid, state]
    for s, lab in st_lab.items():
        parent = cfg["main_canal"]["stages"][s].get("draws_through")
        pt = lines[s].interpolate(0.0)
        nodes.insert(0 if parent is None else 1, {"node": lab, "kind": "main_canal", "level": 0,
                     "parent": st_lab[parent] if parent else None, "stage": lab, "x": pt.x, "y": pt.y,
                     "chainage_m": 0.0, "upstream_m": up[s], "path_m": 0.0})
    nd = pd.DataFrame(nodes)
    nd["pump"] = nd.get("pump", pd.Series(False, index=nd.index)).fillna(False).astype(bool)
    nd.loc[nd.kind.isin(["main_pump", "secondary_pump"]), "pump"] = True
    return {"nodes": nd, "edges": pd.DataFrame(edges), "parcels": p, "levels": levels, "blocks": blocks}


# ---------------------------------------------------------------- aggregates, sizing, pumps
def descendants_parcels(nodes, parcels):
    """node -> index of farm parcels below it."""
    p = parcels[parcels.status == "reached"]
    out = {}
    for col in ("outlet", "unit", "secondary", "main"):
        for k, g in p.groupby(col):
            out[k] = g.index
    sec_par = nodes.set_index("node").parent
    for k in list(out):                                         # the gate feeding a canal serves the same parcels
        if k.endswith("-S1") or k.endswith("-T1"):
            out[sec_par[k]] = out[k]
    for st in nodes.loc[nodes.kind == "main_canal", "node"]:
        stages = [st] + list(nodes.loc[(nodes.kind == "main_canal") & (nodes.parent == st), "node"])
        mains = nodes.loc[nodes.kind.isin(["main_gate", "main_pump"]) & nodes.stage.isin(stages), "node"]
        out[st] = p.index[p.main.isin(mains)]
    return out


def size_network(net, series, days, cfg=CFG):
    """Capacity (l/s) for every canal, gate, pump and outlet by the one sizing rule, bottom-up with losses."""
    s = cfg["sizing"]
    nd, p = net["nodes"].copy(), net["parcels"]
    reached = p[p.status == "reached"]
    idx = {pid: i for i, pid in enumerate(reached.index)}
    S = series                                                  # rows aligned with `reached`
    to_lps = 1000.0 / (days * 86400.0)
    keep = lambda pct, m: (1 - pct / 100.0) ** (np.asarray(m, float) / 1000.0)  # noqa: E731
    node = nd.set_index("node")
    agg = {}
    # outlets
    for oid, g in reached.groupby("outlet"):
        agg[oid] = S[[idx[i] for i in g.index]].sum(0)
    # tertiary canals and their gates: outlets with tertiary losses
    tg = node[node.kind == "tertiary_gate"]
    for tid, g in tg.groupby("parent"):
        v = sum(agg[o] / keep(s["loss_pct_per_km"]["tertiary"], node.at[o, "path_m"]) for o in g.index)
        agg[tid] = v
        agg[node.at[tid, "parent"]] = v
    # secondary canals and main offtakes
    for sid, g in node[node.parent.isin(node.index[node.kind == "secondary_canal"])].groupby("parent"):
        v = np.zeros(S.shape[1])
        for u, r in g.iterrows():
            if r.kind in ("secondary_gate", "secondary_pump", "direct_outlet"):
                v = v + agg[u] / keep(s["loss_pct_per_km"]["secondary"], r.path_m)
        agg[sid] = v
        agg[node.at[sid, "parent"]] = v
    # main canal sections
    mains = node[node.kind.isin(["main_gate", "main_pump"])]
    stage_rows = node[node.kind == "main_canal"]
    for st in list(stage_rows.index)[::-1]:                     # downstream section first
        g = mains[mains.parent == st]
        v = sum((agg[m] / keep(cfg["main_canal"]["loss_pct_per_km"], r.chainage_m) for m, r in g.iterrows()), np.zeros(S.shape[1]))
        for child in stage_rows.index[stage_rows.parent == st]:
            v = v + agg[child] / keep(cfg["main_canal"]["loss_pct_per_km"], node.at[child, "upstream_m"] - node.at[st, "upstream_m"])
        agg[st] = v
    ha_irr = {}
    below = descendants_parcels(nd, p)
    irr = reached[reached.canal_demand == "canal demand"].area_ha
    for k, ix in below.items():
        ha_irr[k] = float(irr.reindex(ix).sum())
    rnd = s["rounding_lps"]
    mins = s["flow_class_min_open_lps"]
    rows = []
    for r in nd.itertuples():
        if r.kind not in CAP_KINDS or r.node not in agg:
            rows.append({"node": r.node})
            continue
        lps = agg[r.node] * to_lps
        p90 = float(np.quantile(lps, s["percentile"]))
        floor = s["floor_lps_per_ha"] * ha_irr.get(r.node, 0.0)
        rule = max(p90, floor) * s["headroom"]
        fc = flow_class(r.kind)
        step = rnd[{"main": "main", "secondary": "secondary", "tertiary": "tertiary", "outlet": "outlet"}[fc]]
        cap = math.ceil(rule / step - 1e-9) * step
        basis = "P90 need incl. losses" if p90 >= floor else "0.8 l/s/ha floor"
        if rule == 0:
            basis = "no canal demand (reached, not irrigated)"
        if fc in mins and cap < mins[fc]:
            cap, basis = float(mins[fc]), f"{fc} minimum open flow"
        if r.kind == "main_canal" and r.parent is None:
            basis_rule, cap, basis = cap, float(cfg["main_canal"]["capacity_lps"]), cfg["main_canal"]["capacity_basis"]
        else:
            basis_rule = cap
        if r.kind == "main_canal" and r.parent is not None:
            cap = min(cap, float(cfg["main_canal"]["capacity_lps"]))
        rows.append({"node": r.node, "p90_lps": round(p90, 1), "floor_lps": round(floor, 1), "rule_lps": round(basis_rule, 1),
                     "capacity_lps": float(cap), "capacity_basis": basis, "flow_class": fc})
    caps = pd.DataFrame(rows).set_index("node")
    nd = nd.join(caps, on="node")
    nd["min_open_lps"] = [max(s["min_open_share"] * c, mins.get(fc, 0.0)) if pd.notna(c) and fc in mins else None
                          for c, fc in zip(nd.capacity_lps, nd.flow_class)]
    lo, hi = s["tertiary_stream_lps"]
    nd["stream_flag"] = None
    t = nd.kind == "tertiary_canal"
    nd.loc[t & (nd.capacity_lps > hi), "stream_flag"] = "above tertiary stream band"
    nd.loc[t & (nd.capacity_basis == "tertiary minimum open flow"), "stream_flag"] = "small tertiary raised to 20 l/s"
    return nd


def flow_class(kind):
    return {"main_canal": "main", "main_gate": "secondary", "main_pump": "secondary", "secondary_canal": "secondary",
            "secondary_gate": "tertiary", "secondary_pump": "tertiary", "tertiary_canal": "tertiary",
            "direct_outlet": "tertiary", "tertiary_gate": "outlet"}.get(kind)


def add_pumps(nd, cfg=CFG, override=None):
    pc = cfg["pumps"]
    nd = nd.copy()
    for c in ("pump_units", "unit_lps", "station_lps", "run_windows", "pump_basis"):
        nd[c] = None
    over = {o["node"]: o for o in (override or [])}
    for i, r in nd.iterrows():
        o = over.get(r.node)
        if o is not None:
            is_pump = o["kind"] == "pump"
            nd.at[i, "pump"] = is_pump
            if r.kind in ("main_gate", "main_pump"):
                nd.at[i, "kind"] = "main_pump" if is_pump else "main_gate"
            elif r.kind in ("secondary_gate", "secondary_pump"):
                nd.at[i, "kind"] = "secondary_pump" if is_pump else "secondary_gate"
            if is_pump:
                k, u = int(o.get("units") or pump_units(r.capacity_lps, cfg)[0]), int(o.get("unit_lps") or pump_units(r.capacity_lps, cfg)[1])
                nd.loc[i, ["pump_units", "unit_lps", "station_lps"]] = [k, u, float(k * u)]
                nd.at[i, "run_windows"], nd.at[i, "pump_basis"] = ";".join(pc["run_windows"]), "real list (owner override)"
            continue
        if bool(r.pump) and pd.notna(r.capacity_lps):
            k, u = pump_units(r.capacity_lps, cfg)
            nd.loc[i, ["pump_units", "unit_lps", "station_lps"]] = [k, u, float(k * u)]
            nd.at[i, "run_windows"], nd.at[i, "pump_basis"] = ";".join(pc["run_windows"]), pc["label"]
    return nd


def node_aggregates(nd, parcels, cfg=CFG):
    """n_parcels, ha, irrigable ha, ha per v1.5 farm class and per terrain state, majority community, label."""
    p = parcels[parcels.status == "reached"]
    below = descendants_parcels(nd, parcels)
    farm = cfg["land_types"]["farm_classes"]
    rows = []
    for r in nd.itertuples():
        ix = below.get(r.node)
        if ix is None or r.kind == "tail_escape":
            ix = below.get(r.parent) if r.kind == "tail_escape" else None
        g = p.reindex(ix) if ix is not None else p.iloc[:0]
        com = g.groupby("community").area_ha.sum().sort_values(ascending=False, kind="mergesort")
        row = {"node": r.node, "n_parcels": int(len(g)) if r.kind != "tail_escape" else 0,
               "ha": round(float(g.area_ha.sum()), 4) if r.kind != "tail_escape" else 0.0,
               "ha_irrigable": round(float(g.area_ha[g.canal_demand == "canal demand"].sum()), 4) if r.kind != "tail_escape" else 0.0,
               "community": com.index[0] if len(com) else None,
               "communities": ";".join(com.index) if len(com) else ""}
        for c in farm:
            row[f"ha_{c}"] = round(float(g.area_ha[g.cls == c].sum()), 4) if r.kind != "tail_escape" else 0.0
        for st in STATES:
            row[f"ha_{st.replace(' ', '_')}"] = round(float(g.area_ha[g.terrain_state == st].sum()), 4) if r.kind != "tail_escape" else 0.0
        rows.append(row)
    a = pd.DataFrame(rows).set_index("node")
    nd = nd.join(a, on="node")
    sec_name = {"main_canal": "main canal", "main_gate": "main-canal gate", "main_pump": "pump station on the main canal",
                "secondary_canal": "secondary canal", "secondary_gate": "secondary gate", "secondary_pump": "pump station on the secondary canal",
                "tertiary_canal": "tertiary canal", "tertiary_gate": "tertiary gate", "direct_outlet": "direct outlet",
                "tail_escape": "tail escape"}
    nd["kind_label"] = nd.kind.map(sec_name)
    nd["label"] = [f"{n} · {c}" if isinstance(c, str) and c else n for n, c in zip(nd.node, nd.community)]
    return nd


def section_of(nd, cfg=CFG):
    """upper / lower stage I by half of stage I served hectares; stage II."""
    nd = nd.copy()
    names = cfg["main_canal"]["sections"]["names"]
    m = nd[nd.kind.isin(["main_gate", "main_pump"])].sort_values(["stage", "chainage_m"])
    s1 = m[m.stage == "I"]
    half = s1.ha.sum() / 2.0
    cum = s1.ha.cumsum() - s1.ha / 2.0
    sec = {n: (names[0] if c < half else names[1]) for n, c in zip(s1.node, cum)}
    sec.update({n: names[2] for n in m[m.stage == "II"].node})
    root_of = {}
    par = nd.set_index("node").parent.to_dict()
    for n in nd.node:
        cur = n
        while cur is not None and cur not in sec:
            cur = par.get(cur)
        root_of[n] = sec.get(cur)
    nd["section"] = nd.node.map(root_of)
    return nd


