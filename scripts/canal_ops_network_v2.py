"""Tree-shaped synthetic canal network v2 (locked plan v6 sections 2, 2a and 2c) on land types v1.5.

Only the main canal line is real (data/source/lower_hrazdan.geojson). Everything below it is generated by the fixed
rules in config/canal_ops_network_v2.json. The SQL archive is not read at all (owner decision 2); the build runs under
wp_core.read_guard, which records every file read into the manifest and refuses archive or parent-project paths.

  1. Universe: all 22,802 observed-zone parcels. Farm parcels (field land, perennial, greenhouse classes of v1.5) are
     all reached; non-farm, unclassified and not-classifiable parcels are listed as not served, so hectares reconcile
     by class to 10,339.3 ha. The 2,945 parcels without lon/lat get the representative point of their cadastral
     geometry; a missing community comes from the outline containing that point (or the nearest within 500 m).
  2. Each farm parcel goes to the nearest stage line (chainage, distance, side). Secondary blocks are (stage, side,
     1.5 km window) groups of at least 115 ha; parcel groups (outlets) are one 250 m cell of one community in a block.
  3. Per block an exact Euclidean minimum spanning tree over the outlets and the main-canal gate (the canal point
     nearest the block). The tree is cut bottom-up into tertiary canals of 25-60 ha whose gates sit on the secondary
     canal; the remaining trunk is the secondary canal; parcel groups on it get direct outlets; its tail gets an escape.
  4. Terrain per tertiary block or direct outlet (never per parcel): a canal level that only falls downstream, minus
     0.3 m per gate and 0.5 m per km of ditch, against the area-weighted median parcel terrain: gravity / pumping /
     terrain uncertain (+-3 m) / terrain not covered. Pumping blocks get pump stations in whole units with night-tariff
     windows; a secondary that starts above the canal is lifted by a pump station on the main canal. No head figures.
  5. One sizing rule at every level: max(P90 2021-2024 gross need incl. downstream losses, 0.8 l/s/ha) x 1.10, with
     class minimums (100 l/s secondary, 20 l/s tertiary) and the main canal at 12 m3/s (owner).

  canal_ops_network_v2.py build   -> data/analysis/canal_ops_sim_v1/network_v2/
     nodes.parquet         every canal, gate, pump, outlet and escape: id, kind, level, parent, label, ha by class,
                           capacity, terrain state (aggregates; no parcel ids or cadastral codes)
     edges.parquet         canal segments (lon/lat), per canal id
     parcel_node.parquet   per parcel (internal only; never served): status, demand class, outlet, unit, secondary
     id_map_v1_to_v2.parquet, id_changes.parquet, network.geojson, summary.json (QA), manifest.json
"""
