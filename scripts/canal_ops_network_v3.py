"""Terrain-routed synthetic canal network v3 (owner-approved terrain rebuild design, 2026-11-02).

Only the main canal line is real. Everything below it is generated by the fixed rules in
config/canal_ops_network_v3.json, frozen before the first build. The SQL archive is not read at all; the build runs under
wp_core.read_guard. Network v2 stays as it was; v3 writes data/analysis/canal_ops_sim_v1/network_v3/ in v2's schema.

What changes against v2 (design docs/CANAL_NETWORK_TERRAIN_REBUILD_DESIGN_2026_11_02_EN.md and the owner's notes):
  1. Terrain: Copernicus GLO-30 (30 m) smoothed against trees and buildings, on a 10 m routing grid.
  2. Canals never cross farm land: farm-parcel interiors are closed; canals run on parcel borders, in the gaps between
     parcels, on non-farm land and along roads (OSM). The main canal is a barrier crossed only at offtakes.
  3. Water level: every canal carries a level that never rises; it stands at most 1 m above the ground (a drop
     structure lowers it where the ground falls faster) and the ground stands at most 1.5 m above it (no deeper cuts,
     no siphons). The routes come from a highest-water-level search, so canals follow ridges and contours by themselves.
  4. Command: a parcel is served by the gate that brings the highest water to its border; gravity when its high ground
     (P90) plus freeboard, gate drop and field-channel fall stays below that level; units by the 85 % rule; +-3 m band.
  5. Pumping (owner): one pump station per lifted land cluster, at the canal (main canal or a gravity secondary). It
     pushes water through a rising main into a chamber at the cluster's high point; gravity ditches run downhill from
     there; the gates below a pump are ordinary gates.
Sizing, aggregates, pump units, sections and the id scheme are v2's (scripts/canal_ops_network_v2.py).

  canal_ops_network_v3.py build   -> data/analysis/canal_ops_sim_v1/network_v3/ (same files as network_v2, plus
                                     id_map_v2_to_v3.parquet instead of the v1 map)
"""
