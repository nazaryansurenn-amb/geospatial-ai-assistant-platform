# ---------------------------------------------------------------- grid and terrain
class Grid:
    """North-up grid with a closed one-cell frame; cell (r, c) has index r * W + c and centre (x, y)."""

    def __init__(self, left, top, res, W, H):
        self.left, self.top, self.res, self.W, self.H = left, top, res, W, H
        self.transform = (res, 0.0, left, 0.0, -res, top)

    def xy(self, idx):
        idx = np.asarray(idx)
        r, c = np.divmod(idx, self.W)
        return self.left + (c + 0.5) * self.res, self.top - (r + 0.5) * self.res

    def rc(self, x, y):
        c = np.floor((np.asarray(x, float) - self.left) / self.res).astype(int)
        r = np.floor((self.top - np.asarray(y, float)) / self.res).astype(int)
        return r, c

    def idx(self, x, y):
        r, c = self.rc(x, y)
        return r * self.W + c

    def affine(self):
        from rasterio.transform import Affine
        return Affine(self.res, 0.0, self.left, 0.0, -self.res, self.top)


def make_grid(xs, ys, cfg=CFG):
    t = cfg["terrain_source"]
    b, big = t["domain_buffer_m"], t["dem_grid_m"]
    x0 = math.floor((min(xs) - b) / big) * big
    x1 = math.ceil((max(xs) + b) / big) * big
    y0 = math.floor((min(ys) - b) / big) * big
    y1 = math.ceil((max(ys) + b) / big) * big
    res = t["grid_m"]
    return Grid(x0, y1, res, int(round((x1 - x0) / res)), int(round((y1 - y0) / res)))


def smooth(z):
    """25th percentile of each 3 x 3 window, then a 3 x 3 mean (edges repeat)."""
    def stack(a):
        p = np.pad(a, 1, mode="edge")
        return np.stack([p[i:i + a.shape[0], j:j + a.shape[1]] for i in range(3) for j in range(3)])
    lo = np.percentile(stack(z), 25, axis=0)
    return stack(lo).mean(0)


def load_dem(grid, cfg=CFG):
    """Smoothed GLO-30 ground on the routing grid (float64, metres)."""
    import rasterio
    from rasterio.transform import Affine
    from rasterio.warp import Resampling, reproject
    t = cfg["terrain_source"]
    big = t["dem_grid_m"]
    k = big // grid.res
    W30, H30 = grid.W // k, grid.H // k
    a30 = Affine(big, 0.0, grid.left, 0.0, -big, grid.top)
    z30 = np.full((H30, W30), np.nan, dtype="float64")
    with rasterio.open(ROOT / cfg["inputs"]["terrain_dem"]) as src:
        reproject(rasterio.band(src, 1), z30, dst_transform=a30, dst_crs=cfg["crs"], resampling=Resampling.bilinear,
                  dst_nodata=np.nan)
    if np.isnan(z30).any():
        raise ValueError("the terrain tile does not cover the routing grid")
    z30 = smooth(z30)
    z = np.empty((grid.H, grid.W), dtype="float64")
    reproject(z30, z, src_transform=a30, src_crs=cfg["crs"], dst_transform=grid.affine(), dst_crs=cfg["crs"],
              resampling=Resampling.bilinear)
    return z


# ---------------------------------------------------------------- open cells
def load_polygons(parcels, grid, cfg=CFG):
    """Cadastral polygons in the grid: (all polygons, soft flag, polygon per observed-zone parcel id)."""
    import geopandas as gpd
    cad = gpd.read_file(ROOT / cfg["inputs"]["cadastre"], columns=["cadastre_code"]).to_crs(cfg["crs"])
    box = shapely.box(grid.left, grid.top - grid.H * grid.res, grid.left + grid.W * grid.res, grid.top)
    cad = cad[cad.intersects(box)].reset_index(drop=True)
    ids = pd.read_parquet(ROOT / cfg["inputs"]["parcel_ids"], columns=["internal_parcel_id", "cadastre_code"])
    ids = ids[ids.internal_parcel_id.isin(parcels.index)]
    cls = ids.assign(cls=parcels.cls.reindex(ids.internal_parcel_id).to_numpy()).drop_duplicates("cadastre_code")
    soft_codes = set(cls.loc[cls.cls.isin(OPEN_SOFT), "cadastre_code"])
    soft = cad.cadastre_code.isin(soft_codes).to_numpy()
    geom = cad.drop_duplicates("cadastre_code").set_index("cadastre_code").geometry
    by_pid = {pid: geom.get(code) for pid, code in zip(ids.internal_parcel_id, ids.cadastre_code)}
    return cad.geometry.values, soft, by_pid


def open_cells(grid, polys, soft, lines, cfg=CFG):
    """Cell classes (closed / road / border / non-farm) and the main-canal mask, as flat bytearrays."""
    import geopandas as gpd
    from rasterio.features import rasterize
    r = cfg["routing"]
    band = r["border_band_m"]
    shape = (grid.H, grid.W)
    tr = grid.affine()
    inner = shapely.buffer(polys, -band)
    keep = ~shapely.is_empty(inner)
    cls = np.full(shape, BORDER, dtype="uint8")
    hard = [(g, 1) for g, k, s in zip(inner, keep, soft) if k and not s]
    softs = [(g, 1) for g, k, s in zip(inner, keep, soft) if k and s]
    if softs:
        cls[rasterize(softs, out_shape=shape, transform=tr, fill=0, dtype="uint8") == 1] = NONFARM
    if hard:
        cls[rasterize(hard, out_shape=shape, transform=tr, fill=0, dtype="uint8") == 1] = CLOSED
    roads = gpd.read_file(ROOT / cfg["inputs"]["roads"]).to_crs(cfg["crs"])
    rb = shapely.buffer(roads.geometry.values, roads.buffer_width_m.fillna(4.0).to_numpy() / 2.0 + r["road_band_extra_m"])
    road = rasterize([(g, 1) for g in rb], out_shape=shape, transform=tr, fill=0, dtype="uint8") == 1
    cls[road & (cls != CLOSED)] = ROAD                      # a track drawn across a farm parcel does not open it
    canal = rasterize([(ln, 1) for ln in lines.values()], out_shape=shape, transform=tr, fill=0, all_touched=True,
                      dtype="uint8")
    cls[canal == 1] = CLOSED
    cls[0, :] = cls[-1, :] = cls[:, 0] = cls[:, -1] = CLOSED
    return cls, canal


# ---------------------------------------------------------------- highest-water-level search
def search(cls, canal, ground, W, seeds, slope_m_per_km, cfg=CFG, region=None):
    """Label-setting search: each open cell keeps the highest water level a route can bring to it (minus a small
    route penalty that prefers roads). seeds: (cell, level, label, pred). Returns (level, label, pred) arrays."""
    wlc = cfg["water_level"]
    emb, cut = wlc["max_above_ground_m"], wlc["max_cut_m"] - wlc["routing_cut_reserve_m"]
    pr = cfg["routing"]["penalty_m_per_m"]
    pen_rate = [0.0, pr["road"], pr["border"], pr["non_farm"]]
    s = slope_m_per_km / 1000.0
    N = len(cls)
    inf = float("inf")
    best = array("d", [inf]) * N
    wl = array("d", [float("nan")]) * N
    pn = array("d", [0.0]) * N
    lab = array("i", [-1]) * N
    pred = array("i", [-1]) * N
    done = bytearray(N)
    heap = []
    for c, w, label, p in seeds:
        k = -w
        if k < best[c]:
            best[c], wl[c], lab[c], pred[c] = k, w, label, p
            heap.append((k, c))
    heapq.heapify(heap)
    d2 = 10.0 * math.sqrt(2.0)
    nbs = [(-W, 10.0, 0, 0), (W, 10.0, 0, 0), (-1, 10.0, 0, 0), (1, 10.0, 0, 0),
           (-W - 1, d2, -W, -1), (-W + 1, d2, -W, 1), (W - 1, d2, W, -1), (W + 1, d2, W, 1)]
    pop, push = heapq.heappop, heapq.heappush
    while heap:
        k, i = pop(heap)
        if done[i] or k > best[i]:
            continue
        done[i] = 1
        w, p, label = wl[i], pn[i], lab[i]
        for off, d, a, b in nbs:
            j = i + off
            cj = cls[j]
            if not cj or done[j]:
                continue
            if region is not None and not region[j]:
                continue
            if a and (canal[i + a] or canal[i + b]):
                continue
            g = ground[j]
            w2 = w - s * d
            if g > w2 + cut:
                continue
            if w2 > g + emb:
                w2 = g + emb
            p2 = p + pen_rate[cj] * d
            k2 = p2 - w2
            if k2 < best[j]:
                best[j], wl[j], pn[j], lab[j], pred[j] = k2, w2, p2, label, i
                push(heap, (k2, j))
    return np.frombuffer(wl, dtype="float64"), np.frombuffer(lab, dtype="int32"), np.frombuffer(pred, dtype="int32")


def nearest_route(cls, W, start, is_target, region=None):
    """Shortest route over open cells from start to the first cell for which is_target(cell) holds: (path, target)."""
    d2 = 10.0 * math.sqrt(2.0)
    nbs = [(-W, 10.0), (W, 10.0), (-1, 10.0), (1, 10.0), (-W - 1, d2), (-W + 1, d2), (W - 1, d2), (W + 1, d2)]
    dist = {start: 0.0}
    pred = {start: -1}
    heap = [(0.0, start)]
    done = set()
    while heap:
        d, i = heapq.heappop(heap)
        if i in done:
            continue
        done.add(i)
        if is_target(i):
            path = [i]
            while pred[path[-1]] >= 0:
                path.append(pred[path[-1]])
            return path[::-1], i
        for off, step in nbs:
            j = i + off
            if not cls[j] or j in done or (region is not None and not region[j]):
                continue
            nd = d + step
            if nd < dist.get(j, float("inf")):
                dist[j], pred[j] = nd, i
                heapq.heappush(heap, (nd, j))
    return None, None


# ---------------------------------------------------------------- main canal
def pava_down(y):
    """Least-squares non-increasing fit (pool adjacent violators)."""
    vals, wts, cnt = [], [], []
    for v in y:
        vals.append(float(v)); wts.append(1.0); cnt.append(1)
        while len(vals) > 1 and vals[-2] < vals[-1]:
            v2_, w2_, c2_ = vals.pop(), wts.pop(), cnt.pop()
            vals[-1] = (vals[-1] * wts[-1] + v2_ * w2_) / (wts[-1] + w2_)
            wts[-1] += w2_
            cnt[-1] += c2_
    return np.repeat(vals, cnt)


def canal_levels(lines, terrain, cfg=CFG):
    prof = n1.canal_profile(lines, terrain, v2.canal_cfg(cfg))
    out, cap = [], np.inf
    end_level = np.inf
    for stage, s in cfg["main_canal"]["stages"].items():
        p = prof[prof.stage == stage].sort_values("chainage_m").copy()
        if s.get("draws_through"):
            cap = min(cap, end_level)
        ok = p.elev.notna().to_numpy()
        lev = np.full(len(p), np.nan)
        lev[ok] = np.minimum(pava_down(p.elev.to_numpy()[ok]), cap)
        p["level"] = lev
        end_level = float(p.level.dropna().iloc[-1])
        out.append(p)
    return pd.concat(out, ignore_index=True)


def canal_cells(grid, canal, lines, levels):
    """Main-canal cells: stage, chainage, level, and the flow direction there."""
    idx = np.flatnonzero(canal.ravel())
    x, y = grid.xy(idx)
    pts = shapely.points(x, y)
    names = list(lines)
    dist = np.vstack([shapely.distance(pts, lines[s]) for s in names])
    k = dist.argmin(0)
    rows = []
    for i, s in enumerate(names):
        m = k == i
        ch = shapely.line_locate_point(lines[s], pts[m])
        p0 = shapely.line_interpolate_point(lines[s], np.clip(ch - 5, 0, lines[s].length))
        p1 = shapely.line_interpolate_point(lines[s], np.clip(ch + 5, 0, lines[s].length))
        lv = levels[levels.stage == s]
        rows.append(pd.DataFrame({"cell": idx[m], "stage": s, "chainage_m": ch,
                                  "level": np.interp(ch, lv.chainage_m.to_numpy(), lv.level.to_numpy()),
                                  "dx": shapely.get_x(p1) - shapely.get_x(p0), "dy": shapely.get_y(p1) - shapely.get_y(p0),
                                  "x": x[m], "y": y[m]}))
    return pd.concat(rows, ignore_index=True).sort_values(["stage", "chainage_m", "cell"]).reset_index(drop=True)


def canal_seeds(cc, grid, cls, ground, cfg=CFG, side_of_label=None):
    """Seeds from main-canal cells into the open neighbours on one side. cc rows need a 'label' column and 'side'
    ('left', 'right' or 'both'). Returns [(cell, level, label, pred)]."""
    W = grid.W
    drop = cfg["water_level"]["drop_per_gate_m"]
    wlc = cfg["water_level"]
    emb, cut = wlc["max_above_ground_m"], wlc["max_cut_m"] - wlc["routing_cut_reserve_m"]
    s = wlc["routing_slope_m_per_km"] / 1000.0
    out = []
    for r in cc.itertuples():
        w0 = r.level - drop
        for off in (-W, W, -1, 1, -W - 1, -W + 1, W - 1, W + 1):
            j = r.cell + off
            if not cls[j]:
                continue
            jx, jy = grid.xy(j)
            sd = "left" if r.dx * (jy - r.y) - r.dy * (jx - r.x) > 0 else "right"
            sides = ("left", "right") if r.side == "both" else (r.side,)
            if sd not in sides:
                continue
            g = ground[j]
            w = w0 - s * math.hypot(jx - r.x, jy - r.y)
            if g > w + cut:
                continue
            lab = r.label if r.side != "both" else r.label * 2 + (sd == "right")
            out.append((int(j), min(w, g + emb), int(lab), int(r.cell)))
    return out


# ---------------------------------------------------------------- parcels on the grid
def parcel_cells(farm, polys_by_pid, grid, cls, ground, cfg=CFG):
    """Per farm parcel: P90 ground inside the polygon and the open access cells within access_m of it."""
    acc_m = cfg["command"]["access_m"]
    W = grid.W
    zf = ground.ravel()
    clsn = np.frombuffer(bytes(cls), dtype="uint8")
    p90, acc = {}, {}
    for pid, r in farm.iterrows():
        g = polys_by_pid.get(pid)
        if g is None or g.is_empty:
            g = shapely.Point(r.x, r.y).buffer(15.0)
        b = g.buffer(acc_m)
        x0, y0, x1, y1 = b.bounds
        r0, c0 = grid.rc(x0, y1)
        r1, c1 = grid.rc(x1, y0)
        r0, c0 = max(int(r0), 1), max(int(c0), 1)
        r1, c1 = min(int(r1), grid.H - 2), min(int(c1), grid.W - 2)
        rr, cc = np.mgrid[r0:r1 + 1, c0:c1 + 1]
        rr, cc = rr.ravel(), cc.ravel()
        xs, ys = grid.left + (cc + 0.5) * grid.res, grid.top - (rr + 0.5) * grid.res
        ids = rr * W + cc
        inside = shapely.contains_xy(g, xs, ys)
        p90[pid] = float(np.percentile(zf[ids[inside]], 90)) if inside.any() else float(zf[grid.idx(r.x, r.y)])
        near = shapely.contains_xy(b, xs, ys)
        a = ids[near]
        acc[pid] = a[clsn[a] > 0]
    return pd.Series(p90), acc


def best_access(acc, wl, pids):
    """Access cell with the highest water level per parcel (None when no route reaches it)."""
    out = {}
    for pid in pids:
        a = acc[pid]
        if not len(a):
            out[pid] = None
            continue
        w = wl[a]
        ok = np.isfinite(w)
        if not ok.any():
            out[pid] = None
            continue
        k = np.flatnonzero(ok)
        j = k[np.lexsort((a[k], -w[k]))[0]]
        out[pid] = int(a[j])
    return out


def shortfall(p90, wl_cell, dist_m, cfg=CFG):
    w = cfg["water_level"]
    return p90 + w["freeboard_m"] + w["drop_per_gate_m"] + w["slope_m_per_km"]["field_channel"] * dist_m / 1000.0 - wl_cell


# ---------------------------------------------------------------- trees
class Tree:
    """Routes of one source kept where they lead to an outlet. root: the cell (or main-canal cell) water enters at."""

    def __init__(self, outlets_ha, pred, stop):
        """outlets_ha: {cell: ha}; pred: predecessor array; stop(cell) -> True for the entry cell (kept as root)."""
        self.parent, self.ha = {}, {}
        self.root = None
        for c, h in outlets_ha.items():
            self.ha[c] = self.ha.get(c, 0.0) + h
        for c in sorted(outlets_ha):
            cur = c
            while cur not in self.parent:
                p = int(pred[cur])
                if stop(cur) or p < 0:
                    self.parent[cur] = None
                    self.root = cur if self.root is None else self.root
                    break
                self.parent[cur] = p
                if stop(p):
                    self.parent[p] = None
                    self.root = p
                    break
                cur = p
        roots = [c for c, p in self.parent.items() if p is None]
        if len(set(roots)) > 1:                                    # several entry cells of one offtake: one root
            r0 = min(roots)
            for r in roots:
                if r != r0:
                    self.parent[r] = r0
            self.root = r0
        self.children = {c: [] for c in self.parent}
        for c, p in self.parent.items():
            if p is not None:
                self.children[p].append(c)
        for c in self.children:
            self.children[c].sort()

    def order(self):
        """Cells root first (pre-order)."""
        out, stack = [], [self.root]
        while stack:
            v = stack.pop()
            out.append(v)
            stack.extend(reversed(self.children[v]))
        return out


def step_m(a, b, W):
    ra, ca = divmod(a, W)
    rb, cb = divmod(b, W)
    return 10.0 * math.hypot(ra - rb, ca - cb)


def split_tiers(t, W, cfg=CFG):
    """secondary cells, and units: {'kind': 'tertiary'|'direct', 'at': secondary cell, 'head': first cell,
    'cells': [...], 'outlets': [...]}."""
    tc = cfg["tree"]
    hi, max_m, lo, dmax = tc["tertiary_max_ha"], tc["tertiary_max_m"], tc["tertiary_cut_min_ha"], tc["direct_max_m"]
    order = t.order()
    acc = {}
    for v in reversed(order):
        acc[v] = t.ha.get(v, 0.0) + sum(acc[c] for c in t.children[v])
    sec = {t.root}
    for v in order:
        if v != t.root and t.parent[v] in sec and acc[v] > hi:
            sec.add(v)

    def subtree(h):
        cells, stack = [], [h]
        while stack:
            v = stack.pop()
            cells.append(v)
            stack.extend(t.children[v])
        return cells

    def longest(h):
        d = {h: 0.0}
        best = 0.0
        stack = [h]
        while stack:
            v = stack.pop()
            for c in t.children[v]:
                d[c] = d[v] + step_m(v, c, W)
                best = max(best, d[c])
                stack.append(c)
        return best

    heads = [v for v in order if v not in sec and t.parent[v] in sec]
    queue = list(heads)
    heads = []
    while queue:                                                    # long hanging branches extend the secondary
        h = queue.pop(0)
        if longest(h) > max_m and t.children[h]:
            sec.add(h)
            v = h
            while True:
                kids = [c for c in t.children[v] if c not in sec]
                if not kids:
                    break
                nxt = max(kids, key=lambda c: (acc[c], -c))
                for c in kids:
                    if c != nxt:
                        queue.append(c)
                if longest(nxt) <= max_m or not t.children[nxt]:
                    queue.append(nxt)
                    break
                sec.add(nxt)
                v = nxt
        else:
            heads.append(h)
    units = []
    for v in sorted(sec):                                           # outlets sitting on the secondary
        if t.ha.get(v, 0.0) > 0:
            units.append({"kind": "direct", "at": v, "head": v, "cells": [], "outlets": [v]})
    for h in sorted(heads):
        cells = subtree(h)
        outs = [c for c in cells if t.ha.get(c, 0.0) > 0]
        if len(outs) == 1 and acc[h] < lo and longest(h) + step_m(t.parent[h], h, W) <= dmax:
            units.append({"kind": "direct", "at": t.parent[h], "head": h, "cells": cells, "outlets": outs})
        else:
            units.append({"kind": "tertiary", "at": t.parent[h], "head": h, "cells": cells, "outlets": outs})
    return sec, units, acc


def path_from(t, start, cells, W):
    """Distance along the tree from start to every cell in cells (cells all below start)."""
    d = {start: 0.0}
    stack = [start]
    want = set(cells) | {start}
    while stack:
        v = stack.pop()
        for c in t.children[v]:
            if c in want:
                d[c] = d[v] + step_m(v, c, W)
                stack.append(c)
    return d


def levels_on_tree(t, sec, units, root_level, ground, W, cfg=CFG, stop_at_root=False):
    """Water level per tree cell with the tier slopes, a gate drop at every tertiary head, drop structures where the
    ground falls faster and the count of cells where the ground stands above the cut limit."""
    w = cfg["water_level"]
    emb, cut, drop = w["max_above_ground_m"], w["max_cut_m"], w["drop_per_gate_m"]
    head_of = {}
    for u in units:
        if u["kind"] == "tertiary":
            head_of[u["head"]] = True
    tier = {}
    for u in units:
        for c in u["cells"]:
            tier[c] = "tertiary" if u["kind"] == "tertiary" else "secondary"
    lev = {t.root: root_level}
    drops = cuts = 0
    for v in t.order()[1:]:
        p = t.parent[v]
        s = w["slope_m_per_km"]["secondary" if v in sec or tier.get(v) == "secondary" else "tertiary"] / 1000.0
        x = lev[p] - s * step_m(p, v, W) - (drop if v in head_of else 0.0)
        g = float(ground[v])
        if x > g + emb:
            x = g + emb
            drops += 1
        if g > x + cut + 1e-9:
            cuts += 1
        lev[v] = x
    return lev, drops, cuts


# ---------------------------------------------------------------- pumping clusters
def clusters_of(pts_xy, ha, link_m, min_ha, join_m):
    """Union of points closer than link_m; groups under min_ha join the nearest larger group within join_m."""
    n = len(pts_xy)
    par = list(range(n))

    def find(a):
        while par[a] != a:
            par[a] = par[par[a]]
            a = par[a]
        return a
    pts = shapely.points(pts_xy[:, 0], pts_xy[:, 1])
    tree = shapely.STRtree(pts)
    a, b = tree.query(pts, predicate="dwithin", distance=link_m)
    for i, j in zip(a, b):
        ri, rj = find(int(i)), find(int(j))
        if ri != rj:
            par[max(ri, rj)] = min(ri, rj)
    lab = np.array([find(i) for i in range(n)])
    tot = pd.Series(ha).groupby(lab).sum()
    small = [g for g in tot.index if tot[g] < min_ha]
    big = [g for g in tot.index if tot[g] >= min_ha]
    if big:
        for g in small:
            m = lab == g
            bm = np.isin(lab, big)
            d = np.min(np.hypot(pts_xy[m][:, None, 0] - pts_xy[bm][None, :, 0], pts_xy[m][:, None, 1] - pts_xy[bm][None, :, 1]), axis=0)
            k = int(np.argmin(d))
            if d[k] <= join_m:
                lab[m] = lab[bm][k]
    return lab


