def build_all(cfg=CFG, guard=None, log=print):
    lines = v2.load_canal(cfg)
    parcels = v2.load_parcels(cfg)
    net = build_network(parcels, lines, cfg, log)
    reached = net["parcels"][net["parcels"].status == "reached"]
    series, days = v2.gross_series(reached.index, reached.ltype.to_numpy(), cfg)
    nd = v2.size_network(net, series, days, cfg)
    nd = v2.node_aggregates(nd, net["parcels"], cfg)
    nd = v2.add_pumps(nd, cfg, cfg["pumps"]["override"])
    nd = v2.section_of(nd, cfg)
    nd["lon"], nd["lat"] = v2.to_wgs(nd.x, nd.y, cfg)
    net["nodes"] = nd
    net["lines"] = lines
    return net


def build(out=OUT, cfg=CFG, log=print):
    out = Path(out)
    with ReadGuard() as guard:
        net = build_all(cfg, guard, log)
        old = pd.read_parquet(ROOT / cfg["inputs"]["network_v2_parcels"])
        idmap = v2.id_map_v1(net["parcels"].reset_index(), cfg)
    out.mkdir(parents=True, exist_ok=True)
    nd, ed, p, lines = net["nodes"], net["edges"].copy(), net["parcels"].reset_index(), net["lines"]
    for c in ("chainage_m", "distance_m", "elev"):
        p[c] = p[c].round(1)
    p = p[v2.PARCEL_COLS]
    ed["lon0"], ed["lat0"] = v2.to_wgs(ed.x0, ed.y0, cfg)
    ed["lon1"], ed["lat1"] = v2.to_wgs(ed.x1, ed.y1, cfg)
    ed["length_m"] = np.hypot(ed.x1 - ed.x0, ed.y1 - ed.y0).round(1)
    changes = v2.id_changes(old, p)
    summary = summarize(net, lines, cfg)
    nd[v2.NODE_COLS].to_parquet(out / "nodes.parquet", index=False)
    ed[["canal", "tier", "lon0", "lat0", "lon1", "lat1", "length_m"]].to_parquet(out / "edges.parquet", index=False)
    p.to_parquet(out / "parcel_node.parquet", index=False)
    changes.to_parquet(out / "id_map_v2_to_v3.parquet", index=False)
    idmap.assign(kind=idmap.kind.str.replace("v2", "v3")).rename(columns={"v2_id": "v3_id"}).to_parquet(
        out / "id_map_v1_to_v3.parquet", index=False)
    v2.write_json(out / "network.geojson", v2.network_geojson(nd, ed[ed.tier != "rising_main"], lines, cfg))
    summary["id_changes_v2_to_v3"] = {f"{k}_{s}": int(v) for (k, s), v in changes.groupby(["kind", "status"]).size().items()}
    summary["read_guard"] = {"violations": guard.violations, "files_read": len(guard.files)}
    v2.write_json(out / "summary.json", summary)
    v2.write_json(out / "manifest.json", {
        "version": cfg["version"], "script": "scripts/canal_ops_network_v3.py", "script_sha256": v2.sha(Path(__file__)),
        "helpers": {f"scripts/{n}": v2.sha(ROOT / "scripts" / n) for n in ("canal_ops_network_v1.py", "canal_ops_network_v2.py")}
        | {"wp_core/read_guard.py": v2.sha(ROOT / "wp_core/read_guard.py")},
        "config": "config/canal_ops_network_v3.json", "config_sha256": v2.sha(CFG_PATH),
        "inputs": {k: v2.sha(ROOT / v) for k, v in cfg["inputs"].items() if k != "not_used" and (ROOT / v).exists()},
        "outputs": {f.name: v2.sha(f) for f in sorted(out.iterdir()) if f.name != "manifest.json"},
        "internal_only": ["parcel_node.parquet", "id_map_v2_to_v3.parquet", "id_map_v1_to_v3.parquet"],
        "files_read": guard.files, "read_guard_violations": guard.violations,
        "not_used": cfg["inputs"]["not_used"]})
    return summary


