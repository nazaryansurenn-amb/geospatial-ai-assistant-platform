def summarize(net, lines, cfg=CFG):
    import re
    nd, p, ed = net["nodes"], net["parcels"], net["edges"]
    q, lt, s = cfg["qa"], cfg["land_types"], cfg["sizing"]
    farm = p[p.farm]
    reached = p[p.status == "reached"]
    by_cls = p.groupby("cls").agg(parcels=("area_ha", "size"), ha=("area_ha", "sum"))
    rch = reached.groupby("cls").area_ha.agg(["size", "sum"])
    recon = {c: {"parcels": int(r.parcels), "ha": round(float(r.ha), 2),
                 "reached_parcels": int(rch["size"].get(c, 0)), "reached_ha": round(float(rch["sum"].get(c, 0.0)), 2),
                 "not_served_ha": round(float(r.ha - rch["sum"].get(c, 0.0)), 2)} for c, r in by_cls.iterrows()}
    cap = nd[nd.capacity_lps.notna()].set_index("node")
    par = nd.set_index("node").parent
    child_gt_parent = [n for n, r in cap.iterrows() if isinstance(par[n], str) and par[n] in cap.index
                       and (r.station_lps if pd.notna(r.get("station_lps")) else r.capacity_lps) > cap.at[par[n], "capacity_lps"] + 1e-9]
    canals = ed[ed.tier != "rising_main"].reset_index(drop=True)
    bad_x, bad_main = v2.crossings(canals, lines)
    secs = nd[nd.kind == "secondary_canal"].node
    esc = set(nd.loc[nd.kind == "tail_escape", "parent"])
    ids_ok = all(re.match(v2.ID_RE[k], n) for n, k in zip(nd.node, nd.kind))
    tree = v2.tree_errors(nd)
    gates = nd[nd.kind.isin(["main_gate", "main_pump", "secondary_gate", "secondary_pump", "tertiary_gate", "direct_outlet"])]
    units = nd[nd.kind.isin(["tertiary_canal", "direct_outlet"])]
    lev = net["levels"]
    falls = all(bool((g.level.dropna().diff().dropna() <= 1e-9).all()) for _, g in lev.groupby("stage"))
    pumps = nd[nd.pump.astype(bool)]
    stage_rule = float(cap.at["I", "rule_lps"]) if "I" in cap.index else np.nan
    head_cols = [c for c in nd.columns if any(w in c.lower() for w in ("head", "lift", "energy", "d_med", "level_m", "elev"))]
    src = net["sources"]
    # water level never rises along any canal, every child head below its parent
    rises = sum(1 for s_ in src for v, pp in s_["tree"].parent.items() if pp is not None and s_["levels"][v] > s_["levels"][pp] + 1e-9)
    # pumps: only at the canal, nothing pumped below a pump
    below_pump = [n for n in pumps.node if isinstance(par.get(n), str) and any(
        par.get(n).startswith(m) for m in pumps.node if m != n and n.startswith(m + "-"))]
    # no canal through farm land: sample every 5 m, distance to the nearest closed interior
    closed = shapely.buffer(np.asarray(net["closed_polys"], dtype=object), -cfg["routing"]["border_band_m"] - 8.0)
    closed = closed[~shapely.is_empty(closed)]
    segs = v2.segments_from(ed)
    samp = []
    for seg in segs:
        L = seg.length
        n = max(int(L // 5.0), 1)
        samp.append(shapely.line_interpolate_point(seg, np.linspace(0, L, n + 1)))
    samp = np.concatenate(samp) if samp else np.array([])
    hit = shapely.STRtree(closed).query(samp, predicate="within")[0] if len(closed) and len(samp) else np.array([])
    tc = nd[nd.kind == "tertiary_canal"]
    lo, hi = s["tertiary_stream_lps"]
    elen = np.hypot(ed.x1 - ed.x0, ed.y1 - ed.y0)
    gravity_units = [u for s_ in src if s_["kind"] == "gravity" for u in s_["units"]]
    tot_drops = sum(s_["drops"] for s_ in src)
    tot_cuts = sum(s_["cuts"] for s_ in src)
    checks = {
        "tree_valid": not tree,
        "ids_match_scheme_and_unique": ids_ok and not nd.node.duplicated().any(),
        "every_gate_reached_and_serves_parcels": bool((gates.n_parcels > 0).all()),
        "all_farm_parcels_reached": bool(farm.outlet.notna().all()) and len(reached) == len(farm),
        "non_farm_not_served": bool(p.loc[~p.farm, "outlet"].isna().all()),
        "ha_reconcile_total": abs(float(p.area_ha.sum()) - q["ha_total"]) <= q["ha_tolerance"],
        "ha_reconcile_by_class": all(abs(v["reached_ha"] + v["not_served_ha"] - v["ha"]) <= q["ha_tolerance"] for v in recon.values()),
        "ha_reconcile_tree": abs(float(nd.loc[nd.kind.isin(["main_gate", "main_pump"]), "ha"].sum()) - float(reached.area_ha.sum())) <= q["ha_tolerance"],
        "each_parcel_one_outlet": bool(reached.outlet.notna().all()) and not reached.index.duplicated().any(),
        "greenhouses_zero_canal_demand": bool((reached.loc[reached.cls == "GREENHOUSE", "canal_demand"] != "canal demand").all()),
        "tail_escape_on_every_secondary": set(secs) == esc,
        "no_canal_crossings": not bad_x,
        "no_crossing_of_main_canal": not bad_main,
        "no_canal_through_farm_land": int(len(np.unique(hit))) == 0,
        "community_in_every_label": bool(nd.loc[nd.kind != "main_canal", "label"].str.contains(" · ").all()),
        "canal_level_falls_downstream": falls,
        "water_level_never_rises_on_any_canal": rises == 0,
        "no_cut_deeper_than_limit": tot_cuts == 0,
        "pumps_only_at_canal_no_pump_below_pump": not below_pump and int(((nd.kind == "direct_outlet") & nd.pump.astype(bool)).sum()) == 0,
        "terrain_state_per_unit": bool(units.terrain_state.isin(STATES).all()),
        "no_child_larger_than_parent": not child_gt_parent,
        "tertiary_streams_20_60_lps": bool(tc.capacity_lps.between(lo, hi).all()),
        "main_canal_12_m3s": float(cap.at["I", "capacity_lps"]) == cfg["main_canal"]["capacity_lps"],
        "need_based_head_within_main_capacity": bool(stage_rule <= cfg["main_canal"]["capacity_lps"]),
        "pumps_whole_units_night_windows": bool(pumps.loc[pumps.capacity_lps.notna(), "pump_units"].apply(lambda v: float(v).is_integer() and v >= 1).all()
                                                and pumps.loc[pumps.capacity_lps.notna(), "run_windows"].eq(";".join(cfg["pumps"]["run_windows"])).all()),
        "no_head_figures_in_outputs": not head_cols,
    }
    ts = reached.groupby("terrain_state").area_ha.agg(["size", "sum"])
    tier_km = {k: round(float(elen[ed.tier == k].sum() / 1000), 1) for k in ("secondary", "tertiary", "rising_main")}
    return {
        "version": cfg["version"], "label": cfg["labels"]["network"], "zone": cfg["labels"]["zone"],
        "synthetic": "real main canal line only; gates, pump stations, canals and outlets generated by fixed rules on the terrain; SQL archive not read",
        "terrain_credit": cfg["terrain_source"]["credit"],
        "reached_note": lt["reached_note"],
        "universe": {"parcels": int(len(p)), "ha": round(float(p.area_ha.sum()), 2)},
        "farm": {"parcels": int(len(farm)), "ha": round(float(farm.area_ha.sum()), 2),
                 "reached_parcels": int(len(reached)), "reached_ha": round(float(reached.area_ha.sum()), 2),
                 "reached_share": round(len(reached) / max(len(farm), 1), 4),
                 "canal_demand_ha": round(float(reached.area_ha[reached.canal_demand == "canal demand"].sum()), 2),
                 "zero_canal_demand_ha": round(float(reached.area_ha[reached.canal_demand != "canal demand"].sum()), 2)},
        "reconcile_by_class": recon,
        "counts": {k: int(v) for k, v in nd.kind.value_counts().sort_index().items()},
        "main_offtakes_by_stage": {k: int(v) for k, v in nd[nd.kind.isin(["main_gate", "main_pump"])].stage.value_counts().sort_index().items()},
        "sections": {k: round(float(v), 2) for k, v in nd[nd.kind.isin(["main_gate", "main_pump"])].groupby("section").ha.sum().items()},
        "terrain": {"label": cfg["terrain"]["label"], "source": cfg["terrain_source"]["dem"],
                    "uncertain_band_m": cfg["terrain"]["uncertain_band_m"], "decision_unit": cfg["terrain"]["decision_unit"],
                    "units_by_state": {k: int(v) for k, v in units.terrain_state.value_counts().items()},
                    "reached_by_state": {k: {"parcels": int(v["size"]), "ha": round(float(v["sum"]), 2)} for k, v in ts.iterrows()},
                    "gravity_units": len(gravity_units),
                    "main_pump_stations": int((nd.kind == "main_pump").sum()),
                    "secondary_pump_stations": int((nd.kind == "secondary_pump").sum()),
                    "left_on_nearest_outlet_parcels": len(net["leftovers"]),
                    "left_on_nearest_outlet_ha": round(float(p.area_ha.reindex(list(net["leftovers"])).sum()), 2)},
        "routing": {"rule": cfg["routing"]["rule"], "grid": net.get("grid"),
                    "cells_held_by_drop_structures": tot_drops, "cells_cut_deeper_than_limit": tot_cuts,
                    "cells_where_level_rises": rises,
                    "edge_points_inside_farm_interiors": int(len(np.unique(hit)))},
        "sizing": {"rule": s["rule"], "need_basis": s["need_basis"], "main_canal_lps": cfg["main_canal"]["capacity_lps"],
                   "need_based_head_lps": round(stage_rule, 1),
                   "capacity_basis": {k: int(v) for k, v in nd.capacity_basis.value_counts().items()},
                   "tertiary_lps": {"min": float(tc.capacity_lps.min()), "median": float(tc.capacity_lps.median()), "max": float(tc.capacity_lps.max())},
                   "stream_flags": {k: int(v) for k, v in nd.stream_flag.value_counts().items()},
                   "child_larger_than_parent": child_gt_parent[:20]},
        "tree": {"errors": tree[:20], "crossings": len(bad_x), "main_canal_crossings": len(bad_main),
                 "km": tier_km, "segments": int(len(ed))},
        "checks": checks,
        "all_checks_pass": all(checks.values()),
    }


