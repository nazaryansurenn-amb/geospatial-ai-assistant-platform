def cached(name, fn):
    """Debug cache for the slow searches (only when V3_DEBUG_CACHE names a folder; the real build never sets it)."""
    import os
    import pickle
    d = os.environ.get("V3_DEBUG_CACHE")
    if not d:
        return fn()
    f = Path(d) / f"{name}.pkl"
    if f.exists():
        return pickle.loads(f.read_bytes())
    v = fn()
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_bytes(pickle.dumps(v, protocol=5))
    return v


def build_network(parcels, lines, cfg=CFG, log=print):
    """Pure apart from reading the terrain, cadastre and roads. Returns nodes, edges, parcels, levels and QA inputs."""
    st_lab = {s: v["label"] for s, v in cfg["main_canal"]["stages"].items()}
    up = n1.upstream_offsets(lines, v2.canal_cfg(cfg))
    p = parcels.sort_index().copy()
    pr = n1.project(p.x.to_numpy(), p.y.to_numpy(), lines)
    pr.index = p.index
    p = p.join(pr)
    farm = p[p.farm].copy()
    cxy = np.vstack([np.asarray(ln.coords) for ln in lines.values()])
    grid = make_grid(np.concatenate([farm.x, cxy[:, 0]]), np.concatenate([farm.y, cxy[:, 1]]), cfg)
    log(f"grid {grid.W} x {grid.H}")
    z = load_dem(grid, cfg)
    terrain = n1.Terrain(z, grid.transform)
    levels = canal_levels(lines, terrain, cfg)
    polys, soft, by_pid = load_polygons(p, grid, cfg)
    cls2d, canal2d = open_cells(grid, polys, soft, lines, cfg)
    cls, canal = bytearray(cls2d.ravel().tobytes()), bytearray(canal2d.ravel().tobytes())
    ground = z.ravel()
    gl = array("d", ground.tolist())
    W = grid.W
    wlc = cfg["water_level"]
    band = cfg["command"]["uncertain_band_m"]
    log(f"open cells {sum(1 for c in cls if c)} of {len(cls)}")
    p90, acc = cached("parcel_cells", lambda: parcel_cells(farm, by_pid, grid, cls, z, cfg))
    farm["p90"] = p90.reindex(farm.index)
    # 1. which canal point commands each farm parcel best (search from every main-canal cell)
    cc = canal_cells(grid, canal2d, lines, levels)
    cc["label"] = np.arange(len(cc))
    cc["side"] = "both"
    wl1, lab1 = cached("pass1", lambda: tuple(np.array(a) for a in search(
        cls, canal, gl, W, canal_seeds(cc, grid, cls, ground, cfg), wlc["routing_slope_m_per_km"], cfg)[:2]))
    a1 = best_access(acc, wl1, farm.index)
    rows = []
    for pid, c in a1.items():
        if c is None:
            continue
        lab = int(lab1[c])
        r = cc.iloc[lab // 2]
        cx, cy = grid.xy(c)
        d = shortfall(farm.at[pid, "p90"], wl1[c], 0.0, cfg)
        rows.append({"pid": pid, "stage": r.stage, "side": "right" if lab % 2 else "left", "chainage_m": r.chainage_m,
                     "area_ha": farm.at[pid, "area_ha"], "d": d})
    s1 = pd.DataFrame(rows).set_index("pid")
    cmd = s1[s1.d <= band]
    oc = cfg["offtakes"]
    blocks = v2.secondary_blocks(cmd, {"secondary_blocks": oc})
    offt = []
    for key, g in cmd.groupby(blocks, sort=True):
        stage, side = g.stage.iloc[0], g.side.iloc[0]
        bins = np.floor(g.chainage_m / oc["point_bin_m"]).astype(int)
        h = g.area_ha.groupby(bins).sum()
        b = int(h.index[np.lexsort((h.index.to_numpy(), -h.to_numpy()))[0]])
        ch = (b + 0.5) * oc["point_bin_m"]
        offt.append({"key": key, "stage": stage, "side": side, "chainage_m": ch, "ha_pass1": float(g.area_ha.sum()),
                     "level": v2.level_at(levels, stage, ch) - wlc["drop_per_gate_m"]})
    offt = pd.DataFrame(offt)
    log(f"offtakes {len(offt)}")
    # 2. the network from the offtakes alone
    seeds_cc = []
    for k, o in offt.iterrows():
        st = cc[cc.stage == o.stage]
        sc = st.iloc[[int(np.argmin((st.chainage_m - o.chainage_m).abs().to_numpy()))]].copy()
        sc["label"], sc["side"], sc["level"] = k, o.side, o.level + wlc["drop_per_gate_m"]
        seeds_cc.append(sc)
    seeds_cc = pd.concat(seeds_cc)
    wl2, lab2, pred2 = cached("pass2", lambda: tuple(np.array(a) for a in search(
        cls, canal, gl, W, canal_seeds(seeds_cc, grid, cls, ground, cfg), wlc["routing_slope_m_per_km"], cfg)))
    a2 = best_access(acc, wl2, farm.index)
    farm["acc"] = pd.Series(a2).reindex(farm.index)
    farm["src"] = [int(lab2[int(c)]) if c is not None and not pd.isna(c) else -1 for c in farm.acc]
    farm["d2"] = [shortfall(farm.at[i, "p90"], wl2[int(c)], 0.0, cfg) if c is not None and not pd.isna(c) else np.inf
                  for i, c in zip(farm.index, farm.acc)]
    grav = farm[np.isfinite(farm.d2) & (farm.d2 <= band)].copy()
    pumpc = farm[~farm.index.isin(grav.index)].copy()
    log(f"gravity parcels {len(grav)} ({grav.area_ha.sum():.0f} ha), pump candidates {len(pumpc)} ({pumpc.area_ha.sum():.0f} ha)")
    is_canal = lambda c: bool(canal[c])                                  # noqa: E731
    sources = []                                                         # gravity offtakes and pumped clusters
    used = bytearray(len(cls))                                           # cells of built canals (closed to later trees)
    for k, o in offt.iterrows():
        g = grav[grav.src == k]
        if g.empty:
            continue
        sources.append(make_source(g, k, o, pred2, wl2, grid, z, cfg, is_canal, kind="gravity", log=log))
    for s in sources:
        for c in s["tree"].parent:
            used[c] = 1
    # 3. pumped clusters: one station at the canal, rising main to a chamber, gravity ditches below it
    left = pumpc.copy()
    pc = cfg["pumping"]
    small = []
    for rnd in range(pc["rounds"]):
        if left.empty:
            break
        lab = clusters_of(left[["x", "y"]].to_numpy(), left.area_ha.to_numpy(), pc["cluster_link_m"], pc["min_cluster_ha"], pc["join_m"])
        groups = sorted(pd.Series(left.index).groupby(lab), key=lambda kv: (-left.area_ha.reindex(kv[1]).sum(), min(kv[1])))
        nxt = []
        for _, pids in groups:
            g = left.loc[list(pids)]
            if g.area_ha.sum() < pc["min_cluster_ha"]:       # owner: one station per land cluster; small pockets
                small.append(g)                               # stay on the network (terrain uncertain)
                continue
            res = pump_cluster(g, sources, cls, canal, used, gl, z, grid, acc, cfg, log)
            if res is None:
                nxt.append(g)
                continue
            src, rest = res
            sources.append(src)
            for c in src["tree"].parent:
                used[c] = 1
            for c in src["rising"]:
                used[c] = 1
            if len(rest):
                nxt.append(g.loc[rest])
        left = pd.concat(nxt) if nxt else left.iloc[:0]
        log(f"pump round {rnd + 1}: {sum(1 for s in sources if s['kind'] != 'gravity')} stations, left {len(left)} parcels ({left.area_ha.sum():.0f} ha)")
    left = pd.concat([left] + small) if small else left
    log(f"left on the nearest outlet: {len(left)} parcels ({left.area_ha.sum():.0f} ha)")
    leftovers = attach_leftovers(left, sources, grid, cfg)
    net = assemble(p, farm, sources, leftovers, lines, levels, up, st_lab, grid, z, canal, cfg)
    net["grid"] = {"W": grid.W, "H": grid.H, "res": grid.res, "open_cells": int(sum(1 for c in cls if c))}
    net["cls"], net["grid_obj"], net["ground"] = cls2d, grid, z
    net["closed_polys"] = [g for g, s in zip(polys, soft) if not s]
    return net


def make_source(g, label, o, pred, wl, grid, z, cfg, is_root, kind, log=print, root_level=None):
    """One offtake (or pumped cluster): outlets, tree, tiers, water levels, unit states."""
    W = grid.W
    cell = cfg["outlets"]["cell_m"]
    key = (np.floor(g.x / cell).astype(int).astype(str) + "_" + np.floor(g.y / cell).astype(int).astype(str) + "|" + g.community)
    outs = {}
    members = {}
    for k2, gg in g.groupby(key.to_numpy(), sort=True):
        cells = gg.acc.astype(int).to_numpy()
        w = wl[cells]
        j = int(cells[np.lexsort((cells, -w))[0]])
        outs[j] = outs.get(j, 0.0) + float(gg.area_ha.sum())
        members.setdefault(j, []).extend(list(gg.index))
    t = Tree(outs, pred, is_root)
    sec, units, acc = split_tiers(t, W, cfg)
    if root_level is None:
        root_level = float(wl[t.root]) if not is_root(t.root) else float(o.level)
    lev, drops, cuts = levels_on_tree(t, sec, units, root_level, z.ravel(), W, cfg)
    ox = {}
    for c, pids in members.items():
        cx, cy = grid.xy(c)
        for pid in pids:
            dist = math.hypot(g.at[pid, "x"] - cx, g.at[pid, "y"] - cy)
            ox[pid] = shortfall(g.at[pid, "p90"], lev[c], dist, cfg)
    d = pd.Series(ox)
    band = cfg["command"]["uncertain_band_m"]
    share = cfg["command"]["block_share"]
    for u in units:
        pids = [pid for c in u["outlets"] for pid in members[c]]
        a = g.area_ha.reindex(pids)
        dd = d.reindex(pids)
        if kind != "gravity":
            u["state"] = "pumping"
        elif float(a[dd <= 0].sum()) >= share * float(a.sum()) - 1e-9:
            u["state"] = "gravity"
        else:
            u["state"] = "terrain uncertain"
        u["pids"] = pids
    return {"kind": kind, "label": label, "o": o, "tree": t, "sec": sec, "units": units, "acc": acc, "levels": lev,
            "members": members, "d": d, "drops": drops, "cuts": cuts, "rising": [], "station": None}


def pump_cluster(g, sources, cls, canal, used, gl, z, grid, acc, cfg, log=print):
    """Chamber at the cluster's high point, gravity ditches from it, rising main to the nearest canal."""
    W = grid.W
    wlc = cfg["water_level"]
    top = g.sort_values(["p90", "area_ha"], ascending=[False, False]).index[0]
    cand = [c for c in acc[top] if not used[c]]
    if not cand:
        cand = [c for pid in g.index for c in acc[pid] if not used[c]]
    if not cand:
        return None
    ch = max(cand, key=lambda c: (z.ravel()[c], -c))
    level = float(g.p90.max()) + wlc["freeboard_m"] + wlc["drop_per_gate_m"]
    xs, ys = g.x.to_numpy(), g.y.to_numpy()
    r0, c0 = grid.rc(xs.min() - 1000, ys.max() + 1000)
    r1, c1 = grid.rc(xs.max() + 1000, ys.min() - 1000)
    reg = np.zeros((grid.H, grid.W), dtype="uint8")
    reg[max(int(r0), 1):min(int(r1), grid.H - 1), max(int(c0), 1):min(int(c1), grid.W - 1)] = 1
    region = bytearray(reg.ravel().tobytes())
    cls_c = bytearray((np.frombuffer(bytes(cls), dtype="uint8") * (1 - np.frombuffer(bytes(used), dtype="uint8"))).astype("uint8").tobytes())
    cls_c[ch] = cls[ch] or BORDER
    bar = bytearray((np.frombuffer(bytes(canal), dtype="uint8") | np.frombuffer(bytes(used), dtype="uint8")).tobytes())
    bar[ch] = 0
    wl, lab, pred = search(cls_c, bar, gl, W, [(ch, level, 0, -1)], wlc["routing_slope_m_per_km"], cfg, region)
    a = best_access({pid: np.array([c for c in acc[pid] if not used[c]] or [], dtype=int) for pid in g.index}, wl, g.index)
    g = g.copy()
    g["acc"] = pd.Series(a).reindex(g.index)
    ok = g.acc.notna()
    g.loc[ok, "d3"] = [shortfall(g.at[i, "p90"], wl[int(c)], 0.0, cfg) for i, c in zip(g.index[ok], g.acc[ok])]
    band = cfg["command"]["uncertain_band_m"]
    served = g[ok & (g.d3 <= band)]
    if served.empty:
        return None
    # rising main: big clusters from the main canal, others from the nearest main canal or gravity secondary
    sec_cells = {}
    if served.area_ha.sum() <= cfg["tree"]["tertiary_max_ha"]:
        for s in sources:
            if s["kind"] == "gravity":
                for c in s["sec"]:
                    if not canal[c]:
                        sec_cells[c] = s
    W_ = W
    gap = cfg["pumping"]["station_spacing_m"]
    taken = [grid.xy(s["station"]) for s in sources if s.get("station") is not None]

    def free(c):                                              # one station per canal point: keep them apart
        x, y = grid.xy(c)
        return all(math.hypot(x - a, y - b) >= gap for a, b in taken)

    def target(i):
        if i in sec_cells and i != ch:
            return free(i)
        for off in (-W_, W_, -1, 1):
            if canal[i + off]:
                return free(i + off)
        return False
    path, hit = nearest_route(cls, W, ch, target)
    if path is None:
        return None
    if hit in sec_cells:
        kind, host = "secondary_pump", sec_cells[hit]
        station = hit
    else:
        kind, host = "main_pump", None
        station = next(hit + off for off in (-W_, W_, -1, 1) if canal[hit + off])
    src = make_source(served, 0, None, pred, wl, grid, z, cfg, lambda c: c == ch, kind="pumping", root_level=level)
    src["kind"], src["host"], src["station"], src["rising"], src["chamber"] = kind, host, station, path, ch
    rest = [i for i in g.index if i not in served.index]
    return src, rest


def attach_leftovers(left, sources, grid, cfg=CFG):
    """Parcels no route commands within the band after the pump rounds join the nearest outlet (terrain uncertain)."""
    if left.empty:
        return {}
    cells, owner, unit_of = [], [], []
    ha = {}
    for k, s in enumerate(sources):
        if s["kind"] == "secondary_pump":                    # its whole cluster is one tertiary: kept within the limit
            continue
        for ui, u in enumerate(s["units"]):
            for c in u["outlets"]:
                cells.append(c)
                owner.append(k)
                unit_of.append((k, ui, u["kind"] == "tertiary" or s["kind"] == "secondary_pump"))
            ha[(k, ui)] = sum(s["tree"].ha.get(c, 0.0) for c in u["outlets"])
    cx, cy = grid.xy(np.asarray(cells))
    hi = cfg["tree"]["tertiary_max_ha"]
    out = {}
    for pid, r in left.sort_values(["x", "y"]).iterrows():
        for j in np.argsort(np.hypot(cx - r.x, cy - r.y), kind="stable"):
            k, ui, capped = unit_of[j]
            if not capped or ha[(k, ui)] + r.area_ha <= hi:
                ha[(k, ui)] += r.area_ha
                out[pid] = (owner[j], cells[j])
                break
    for pid, (k, c) in out.items():
        sources[k]["members"][c].append(pid)
        for u in sources[k]["units"]:
            if c in u["outlets"]:
                u["pids"].append(pid)
                if u["state"] == "gravity":
                    u["state"] = "terrain uncertain"
    return out


# ---------------------------------------------------------------- nodes and edges in v2's schema
def runs(cells, W):
    """Vertices of a cell chain where the step direction changes."""
    if len(cells) < 3:
        return list(cells)
    out = [cells[0]]
    for a, b, c in zip(cells, cells[1:], cells[2:]):
        if b - a != c - b:
            out.append(b)
    out.append(cells[-1])
    return out


def chains(t, cells, start):
    """Cell chains covering the given subtree cells, each starting at its branch point (start = entry cell)."""
    want = set(cells)
    out = []
    stack = [(start, [start])]
    while stack:
        v, ch = stack.pop()
        kids = [c for c in t.children[v] if c in want]
        if not kids:
            if len(ch) > 1:
                out.append(ch)
            continue
        stack.append((kids[0], ch + [kids[0]]))
        for c in kids[1:]:
            stack.append((c, [v, c]))
    return out


def assemble(p, farm, sources, leftovers, lines, levels, up, st_lab, grid, z, canal_mask, cfg=CFG):
    W = grid.W
    nodes, edges = [], []
    p["status"] = np.where(p.farm, "reached", "not served: " + p.cls.map(cfg["land_types"]["not_served"]).fillna("other"))
    p["canal_demand"] = np.where(~p.farm, "none (not served)",
                                 np.where(p.cls.isin(list(cfg["land_types"]["zero_canal_demand"])),
                                          p.cls.map(cfg["land_types"]["zero_canal_demand"]), "canal demand"))
    for c in ("main", "secondary", "unit", "outlet", "terrain_state"):
        p[c] = None
    def cell_xy(c):
        x, y = grid.xy(c)
        if canal_mask[c]:                                    # an entry on the main canal sits on the real line
            pt = shapely.Point(float(x), float(y))
            ln = min(lines.values(), key=lambda ln: ln.distance(pt))
            q = ln.interpolate(ln.project(pt))
            return float(q.x), float(q.y)
        return float(x), float(y)

    def add_edges(canal_id, tier, t, cells, start):
        for ch in chains(t, cells, start):
            v = runs(ch, W)
            for a, b in zip(v, v[1:]):
                (x0, y0), (x1, y1) = cell_xy(a), cell_xy(b)
                edges.append({"canal": canal_id, "tier": tier, "x0": x0, "y0": y0, "x1": x1, "y1": y1})

    # offtakes on the main canal: gravity offtakes and pump stations whose rising main starts at the main canal
    proj = lambda c: n1.project(*[np.array([v]) for v in cell_xy(c)], lines).iloc[0]   # noqa: E731
    mains = []
    for s in sources:
        if s["kind"] == "gravity":
            o = s["o"]
            mains.append((o.stage, float(o.chainage_m), s))
        elif s["kind"] == "main_pump":
            pr = proj(s["station"])
            mains.append((pr.stage, float(pr.chainage_m), s))
    mains.sort(key=lambda m: (list(st_lab).index(m[0]), m[1], m[2]["tree"].root))
    count = {s: 0 for s in st_lab}
    for stage, chain, s in mains:
        count[stage] += 1
        pump = s["kind"] == "main_pump"
        mid = f"{st_lab[stage]}-{'P' if pump else 'G'}{count[stage]:02d}"
        sid = f"{mid}-S1"
        s["main_id"], s["sec_id"] = mid, sid
        t = s["tree"]
        entry = s["station"] if pump else t.root
        mx, my = cell_xy(entry)
        head_state = "pumping" if pump else ("gravity" if any(u["state"] == "gravity" for u in s["units"]) else "terrain uncertain")
        nodes.append({"node": mid, "kind": "main_pump" if pump else "main_gate", "level": 1, "parent": st_lab[stage],
                      "stage": st_lab[stage], "x": mx, "y": my, "chainage_m": round(chain, 1), "path_m": 0.0,
                      "terrain_state": head_state, "block": mid})
        rx, ry = cell_xy(t.root)
        nodes.append({"node": sid, "kind": "secondary_canal", "level": 1, "parent": mid, "stage": st_lab[stage],
                      "x": rx, "y": ry, "path_m": 0.0, "block": mid})
        if pump:
            v = runs(s["rising"], W)
            for a, b in zip(v, v[1:]):
                (x0, y0), (x1, y1) = cell_xy(a), cell_xy(b)
                edges.append({"canal": sid, "tier": "rising_main", "x0": x0, "y0": y0, "x1": x1, "y1": y1})
        place_secondary(s, sid, stage, st_lab, nodes, edges, p, add_edges, cell_xy, W)
    # pump stations on gravity secondaries
    for s in sources:
        if s["kind"] != "secondary_pump":
            continue
        host = s["host"]
        hd = path_from(host["tree"], host["tree"].root, host["sec"], W)
        s["host_path"] = hd.get(s["station"], 0.0)
        host.setdefault("pumps", []).append(s)
    for s in sources:
        if "pumps" in s:
            renumber_children(s, nodes, edges, p, add_edges, cell_xy, W, st_lab)
    for st_, lab in st_lab.items():
        parent = cfg["main_canal"]["stages"][st_].get("draws_through")
        pt = lines[st_].interpolate(0.0)
        nodes.insert(0 if parent is None else 1, {"node": lab, "kind": "main_canal", "level": 0,
                     "parent": st_lab[parent] if parent else None, "stage": lab, "x": pt.x, "y": pt.y,
                     "chainage_m": 0.0, "upstream_m": up[st_], "path_m": 0.0})
    nd = pd.DataFrame(nodes)
    nd["pump"] = nd.kind.isin(["main_pump", "secondary_pump"])
    p["elev"] = farm.p90.reindex(p.index)
    return {"nodes": nd, "edges": pd.DataFrame(edges), "parcels": p, "levels": levels, "sources": sources,
            "leftovers": leftovers}


def place_secondary(s, sid, stage, st_lab, nodes, edges, p, add_edges, cell_xy, W, extra=None):
    """Secondary canal edges, its gates (tertiaries), direct outlets, escape and parcels of one source."""
    t = s["tree"]
    lab = st_lab[stage]
    s["stage_label"] = lab
    secd = path_from(t, t.root, s["sec"], W)
    add_edges(sid, "secondary", t, list(s["sec"]), t.root)
    tu = sorted([u for u in s["units"] if u["kind"] == "tertiary"], key=lambda u: (secd.get(u["at"], 0.0), u["head"]))
    du = sorted([u for u in s["units"] if u["kind"] == "direct"], key=lambda u: (secd.get(u["at"], 0.0), u["head"]))
    items = [("t", secd.get(u["at"], 0.0), u["head"], u) for u in tu] + [("p", ps["host_path"], ps["station"], ps) for ps in (extra or [])]
    items.sort(key=lambda it: (it[1], it[2]))
    lifted = s["kind"] == "main_pump"
    s_state = "pumping" if s["kind"] != "gravity" else None
    k = 0
    for typ, pm, _, u in items:
        k += 1
        if typ == "p":
            place_pump(u, f"{sid}-P{k}", sid, lab, pm, nodes, edges, p, add_edges, cell_xy, W)
            continue
        gid = f"{sid}-G{k}"
        tid = f"{gid}-T1"
        state = s_state or u["state"]
        cells = u["cells"]
        gpos = cells[1] if len(cells) > 1 else cells[0]
        gx, gy = cell_xy(gpos)
        nodes.append({"node": gid, "kind": "secondary_gate", "level": 2, "parent": sid, "stage": lab, "x": gx, "y": gy,
                      "path_m": round(pm, 1), "terrain_state": state, "block": s["main_id"]})
        nodes.append({"node": tid, "kind": "tertiary_canal", "level": 2, "parent": gid, "stage": lab, "x": gx, "y": gy,
                      "path_m": 0.0, "terrain_state": state, "block": s["main_id"]})
        add_edges(tid, "tertiary", t, cells, u["at"])
        td = path_from(t, u["at"], cells, W)
        for j, c in enumerate(sorted(u["outlets"], key=lambda c: (td[c], c)), 1):
            oid = f"{tid}-G{j}"
            ox, oy = cell_xy(c)
            nodes.append({"node": oid, "kind": "tertiary_gate", "level": 3, "parent": tid, "stage": lab, "x": ox, "y": oy,
                          "path_m": round(td[c], 1), "terrain_state": state, "block": s["main_id"]})
            p.loc[s["members"][c], ["main", "secondary", "unit", "outlet", "terrain_state"]] = [s["main_id"], sid, tid, oid, state]
    for k2, u in enumerate(du, 1):
        oid = f"{sid}-D{k2}"
        c = u["outlets"][0]
        state = s_state or u["state"]
        ox, oy = cell_xy(c)
        nodes.append({"node": oid, "kind": "direct_outlet", "level": 2, "parent": sid, "stage": lab, "x": ox, "y": oy,
                      "path_m": round(secd.get(u["at"], 0.0) + (path_from(t, u["at"], u["cells"], W).get(c, 0.0) if u["cells"] else 0.0), 1),
                      "terrain_state": state, "block": s["main_id"]})
        if u["cells"]:
            add_edges(sid, "secondary", t, u["cells"], u["at"])
        p.loc[s["members"][c], ["main", "secondary", "unit", "outlet", "terrain_state"]] = [s["main_id"], sid, oid, oid, state]
    tail = max(s["sec"], key=lambda c: (secd.get(c, 0.0), -c))
    ex, ey = cell_xy(tail)
    nodes.append({"node": f"{sid}-E", "kind": "tail_escape", "level": 2, "parent": sid, "stage": lab, "x": ex, "y": ey,
                  "block": s["main_id"]})


def place_pump(ps, gid, sid, lab, pm, nodes, edges, p, add_edges, cell_xy, W):
    """A pump station on a gravity secondary: its pumped cluster is one tertiary canal below it."""
    t = ps["tree"]
    tid = f"{gid}-T1"
    ps["main_id"], ps["gate_id"] = sid.rsplit("-", 1)[0], gid
    sx, sy = cell_xy(ps["station"])
    nodes.append({"node": gid, "kind": "secondary_pump", "level": 2, "parent": sid, "stage": lab, "x": sx, "y": sy,
                  "path_m": round(pm, 1), "terrain_state": "pumping", "block": ps["main_id"]})
    cx, cy = cell_xy(ps["chamber"])
    nodes.append({"node": tid, "kind": "tertiary_canal", "level": 2, "parent": gid, "stage": lab, "x": cx, "y": cy,
                  "path_m": 0.0, "terrain_state": "pumping", "block": ps["main_id"]})
    v = runs(ps["rising"], W)
    for a, b in zip(v, v[1:]):
        (x0, y0), (x1, y1) = cell_xy(a), cell_xy(b)
        edges.append({"canal": tid, "tier": "rising_main", "x0": x0, "y0": y0, "x1": x1, "y1": y1})
    add_edges(tid, "tertiary", t, list(t.parent), t.root)
    td = path_from(t, t.root, list(t.parent), W)
    outs = sorted(ps["members"], key=lambda c: (td[c], c))
    for j, c in enumerate(outs, 1):
        oid = f"{tid}-G{j}"
        ox, oy = cell_xy(c)
        nodes.append({"node": oid, "kind": "tertiary_gate", "level": 3, "parent": tid, "stage": lab, "x": ox, "y": oy,
                      "path_m": round(td[c], 1), "terrain_state": "pumping", "block": ps["main_id"]})
        p.loc[ps["members"][c], ["main", "secondary", "unit", "outlet", "terrain_state"]] = [ps["main_id"], sid, tid, oid, "pumping"]


def renumber_children(s, nodes, edges, p, add_edges, cell_xy, W, st_lab):
    """Rebuild one secondary's children with its pump stations numbered in line with its gates."""
    sid, mid = s["sec_id"], s["main_id"]
    keep = [n for n in nodes if not (n["node"].startswith(sid + "-") or n["node"] == sid + "-E")]
    nodes[:] = keep
    edges[:] = [e for e in edges if not e["canal"].startswith(sid)]
    p.loc[p.secondary == sid, ["main", "secondary", "unit", "outlet", "terrain_state"]] = [None] * 5
    stage = next(k for k, v in st_lab.items() if v == mid.split("-")[0])
    if s["kind"] == "main_pump":
        v = runs(s["rising"], W)
        for a, b in zip(v, v[1:]):
            (x0, y0), (x1, y1) = cell_xy(a), cell_xy(b)
            edges.append({"canal": sid, "tier": "rising_main", "x0": x0, "y0": y0, "x1": x1, "y1": y1})
    place_secondary(s, sid, stage, st_lab, nodes, edges, p, add_edges, cell_xy, W, extra=s["pumps"])


